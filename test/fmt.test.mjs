import { 묶음, 시험, 같나 } from './harness.mjs';
import { 돈, 억짧게, 숫자, 원, 퍼센트, 율, 숫자읽기 } from '../src/lib/fmt.js';

묶음('돈 표기');

// ★ 검토했던 다른 계산기가 여기서 틀렸다 — 나머지를 천 단위로 반올림해
//   1억 9,600만원을 「1억 10천만원」으로, 1억 400만원을 「1억만원」(=1조 원)으로 보여 주었다.
시험('1억 9,600만원 — 「1억 10천만원」이 되지 않는다', () => 같나(돈(19600), '1억 9,600만원'));
시험('2억 9,700만원', () => 같나(돈(29700), '2억 9,700만원'));
시험('1억 400만원 — 「1억만원」이 되지 않는다', () => 같나(돈(10400), '1억 400만원'));
시험('딱 1억', () => 같나(돈(10000), '1억원'));
시험('1억에서 1만원 모자랄 때', () => 같나(돈(9999), '9,999만원'));
시험('0', () => 같나(돈(0), '0원'));
시험('음수', () => 같나(돈(-5000), '−5,000만원'));
시험('12억 3,456만원', () => 같나(돈(123456), '12억 3,456만원'));
시험('소수는 만원 자리에서 한 번만 반올림', () => 같나(돈(19599.6), '1억 9,600만원'));

묶음('짧은 표기');
시험('3.25억', () => 같나(억짧게(32500), '3.25억'));
시험('끝의 0 은 떼어 낸다', () => 같나(억짧게(32000), '3.2억'));
시험('1억 미만은 만원으로', () => 같나(억짧게(5000), '5,000만원'));

묶음('그 밖의 표기');
시험('천 단위 쉼표', () => 같나(숫자(1234567), '1,234,567'));
시험('원 표기', () => 같나(원(1401387), '1,401,387원'));
시험('퍼센트 — 끝의 0 은 뗀다', () => 같나(퍼센트(4), '4%'));
시험('퍼센트 — 소수는 남긴다', () => 같나(퍼센트(4.25), '4.25%'));
시험('비율 → 퍼센트', () => 같나(율(0.4), '40%'));
시험('글자에서 숫자 읽기', () => 같나(숫자읽기('1,234만원'), 1234));
시험('빈 글자는 0', () => 같나(숫자읽기(''), 0));
