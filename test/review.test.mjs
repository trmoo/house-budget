  //   생애최초를 켜도 달라지지 않는다. 차이를 보려면 실수요에 안 걸리는 조건이어야 한다.
  const 바탕 = { 주택수: 0, 지역: '규제', 매매가: 55000, kb시세: 0, 내소득: 8000, 혼인: '신혼', 방공제: false };
