const S = (o) => ({ ...기본, ...o });

묶음('[1] 추천은 같은 금액으로 견준다');
// ★ 예전에는 갈래마다 **한도까지 꽉 빌린 값**으로 월 상환액을 견줬다. 그러면 금리가 비싸도
//   한도가 작은 쪽이 「매달 덜 낸다」며 이겨서, 3.4% 디딤돌을 제치고 4% 은행이 추천됐다.
시험('금리가 싼 쪽이 추천된다 (예금 4억 · 기본값)', () => {
  const c = 계산(S({ 예금: 40000 }));
  참인가(c.추천, '추천이 없다');
  const 가장싼것 = c.갈래들.filter((g) => g.살수있나).reduce((a, b) => (b.금리 < a.금리 ? b : a));
  같나(c.추천.키, 가장싼것.키);
});
시험('살 수 있는 갈래는 모두 같은 금액을 빌린다 (근저당 차이만큼만 다르다)', () => {
  const c = 계산(S({ 예금: 40000 }));
  const 쓸것 = c.갈래들.filter((g) => g.살수있나).map((g) => g.쓸대출);
  참인가(쓸것.length >= 2, '견줄 갈래가 둘은 있어야 한다');
  const 폭 = Math.max(...쓸것) - Math.min(...쓸것);
  참인가(폭 < 100, `같은 금액이어야 하는데 ${Math.round(폭)}만원이나 벌어졌다`);
});
시험('추천된 쪽이 실제로 매달 가장 적게 낸다', () => {
  const c = 계산(S({ 예금: 40000 }));
  for (const g of c.갈래들.filter((x) => x.살수있나)) {
    참인가(c.추천.월상환원 <= g.월상환원 + 1000, `${g.이름}(${Math.round(g.월상환원)}) 이 더 싸다`);
  }
});
시험('한도까지 빌릴 까닭이 없다 — 종잣돈이 남으면 그만큼 덜 빌린다', () => {
  const c = 계산(S({ 예금: 40000 }));
  const g = c.추천;
  참인가(g.쓸대출 < g.대출, '한도를 다 쓰고 있다');
  가까운가(g.쓸대출, g.대출 - g.차이, 1);
});
시험('종잣돈이 넉넉하면 대출이 0 이고 그렇게 말한다', () => {
  const c = 계산(S({ 예금: 100000, 매매가: 30000 }));
  같나(c.추천.쓸대출, 0);
  참인가(c.추천이유.includes('대출이 필요 없습니다'), c.추천이유);
});

묶음('[2][22] 보금자리론 생애최초는 무주택일 때만');
