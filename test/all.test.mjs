// 「살 수 있는 값」(최대매수가)이 내놓는 답과, 0 이 나올 때의 까닭.
//
// ★ 이 파일은 2026-10-19 에 받은 물음에서 나왔다 — 「살 수 있는 값 0만원」을 보고
//   고장인지 답인지 알 수 없다는 것. 셈은 맞았지만 **까닭을 말하지 않는 것이 결함**이었고,
//   그걸 파다가 진짜 결함도 하나 나왔다(대출이 막히면 현금으로도 못 산다고 했다).

import { 묶음, 시험, 같나, 참인가, 거짓인가, 들었나 } from './harness.mjs';
import { 기본 } from '../src/lib/store.js';
import { 계산, 최대매수가 } from '../src/engine/all.js';

const S = (o) => ({ ...기본, ...o });

묶음('살 수 있는 값 — 보통의 경우');
시험('기본값이면 0 보다 큰 값이 나온다', () => {
  const r = 최대매수가(S({}));
  참인가(r.값 > 0, `${r.값}`);
  같나(r.막힌까닭, null);
});
시험('종잣돈이 늘면 살 수 있는 값도 는다', () => {
  const a = 최대매수가(S({ 예금: 10000 })).값;
  const b = 최대매수가(S({ 예금: 20000 })).값;
  참인가(b > a, `${a} → ${b}`);
});
시험('그 값으로 집을 사면 실제로 살 수 있다 (경계가 맞나)', () => {
  const s = S({});
  const 최대 = 최대매수가(s);
  const c = 계산({ ...s, 매매가: Math.floor(최대.값) });
  참인가(c.추천 && c.추천.살수있나, '경계 안쪽인데 못 산다고 한다');
});
시험('그 값보다 비싸면 못 산다 (경계 바깥)', () => {
  const s = S({});
  const 최대 = 최대매수가(s);
  const c = 계산({ ...s, 매매가: Math.ceil(최대.값) + 500 });
  거짓인가(!!(c.추천 && c.추천.살수있나), '경계 바깥인데 살 수 있다고 한다');
});

묶음('0 이 나올 때는 까닭을 말한다');
시험('종잣돈이 0 이면 「종잣돈없음」', () => {
  const r = 최대매수가(S({ 예금: 0 }));
  같나(r.값, 0);
  같나(r.막힌까닭.종류, '종잣돈없음');
});
시험('살림 준비 비용보다 종잣돈이 적으면 「기본비용초과」', () => {
  // 집값을 0 으로 놓아도 비상금 1,500 + 가전 1,500 + 이사 150 + 등기 ≈ 3,190만원이 든다
  const r = 최대매수가(S({ 예금: 2000 }));
  같나(r.값, 0);
  같나(r.막힌까닭.종류, '기본비용초과');
  참인가(r.막힌까닭.바닥 > r.막힌까닭.씨, '바닥이 종잣돈보다 커야 이 종류가 된다');
  참인가(r.막힌까닭.여윳돈 > 0 && r.막힌까닭.부대 > 0);
});
시험('살림 준비를 줄이면 같은 종잣돈으로도 살 수 있게 된다', () => {
  const r = 최대매수가(S({ 예금: 2000, 가전가구: 0, 비상금개월: 0, 이사비: 0 }));
  참인가(r.값 > 0, `${r.값}`);
});

묶음('대출이 하나도 안 나와도 현금으로는 살 수 있다');
// ★ 2026-10-19 에 잡은 결함 — 규제지역 2주택자는 주담대가 아예 안 나오는데,
//   그때 앱이 「살 수 있는 값 0원」이라고 했다. 현금 1억이 있으면 1억짜리는 살 수 있다.
시험('규제지역 2주택자도 현금으로 살 수 있는 값이 나온다', () => {
  const s = S({ 주택수: 2, 예금: 10000 });
  const c = 계산(s);
  같나(c.추천, null);                       // 세 갈래 모두 막혔다
  참인가(c.현금만 && c.현금만.가능);
  const r = 최대매수가(s);
  참인가(r.값 > 0, `대출이 막혔다고 0원이라 하면 안 된다 (${r.값})`);
});
시험('중과세 때문에 1주택자보다는 적게 산다', () => {
  const 무주택 = 최대매수가(S({ 예금: 10000 })).값;
  const 두채 = 최대매수가(S({ 주택수: 2, 예금: 10000 })).값;
  참인가(두채 < 무주택, `${두채} < ${무주택}`);
});
시험('현금만 갈래는 대출이 0 이고 매매가가 묶는다', () => {
  const c = 계산(S({ 매매가: 30000 }));
  같나(c.현금만.대출, 0);
  들었나(c.현금만.묶은것, '매매가');
});

묶음('한도가 0 인 것과 받을 수 없는 것은 다르다');
시험('소득이 0 이면 받을 수는 있어도 한도가 0 이다', () => {
  const c = 계산(S({ 내소득: 0, 배우자소득: 0 }));
  const 은행 = c.갈래들[0];
  참인가(은행.가능, '소득이 0 이라고 「받을 수 없음」은 아니다');
  같나(은행.한도, 0);
  참인가(은행.한도0, '한도가 0 이라는 표시가 있어야 화면이 「✗ 한도 0」이라고 말한다');
});
시험('보통은 한도0 표시가 켜지지 않는다', () => {
  거짓인가(계산(S({})).갈래들[0].한도0);
});
