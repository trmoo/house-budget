// 정책대출 우대금리 — 깎는 폭 · 중복 규칙 · 상한, 그리고 **한도까지 바뀌는가**.
//
// ★ 우대금리는 꾸밈이 아니다. 보금자리론·디딤돌 한도는 DTI 로 자르는데, DTI 한도는
//   「월 상환 여력으로 갚을 수 있는 원금」을 금리로 역산한 값이라 **금리가 내려가면 한도가 늘어난다.**
//   그래서 이 파일은 금리만이 아니라 한도도 함께 지킨다.

import { 묶음, 시험, 같나, 가까운가, 참인가, 거짓인가 } from './harness.mjs';
import { 기본 } from '../src/lib/store.js';
import { 디딤돌, 보금자리론, 우대셈 } from '../src/engine/policy.js';
import { 월상환액 } from '../src/engine/loan.js';
import { 정책대출 } from '../src/rules.js';

const S = (o) => ({ ...기본, ...o });
const 보금우대 = 정책대출.보금자리론.우대금리;
const 디딤우대 = 정책대출.디딤돌.우대금리;

/** 우대가 하나도 없는 바탕 — 여기서 하나씩 켜 본다 */
const 맨바탕 = {
  혼인: '그외', 생애최초: false, 자녀수: 0, 청약잔액: 0,
  매매가: 50000, kb시세: 0, 내소득: 3000, 배우자소득: 0,
  지역: '지방', 방공제: false,
};

묶음('우대금리 — 표가 제대로 생겼나');
시험('두 상품 모두 상한과 항목을 들고 있다', () => {
  for (const W of [보금우대, 디딤우대]) {
    참인가(W.상한 > 0, `상한 ${W.상한}`);
    참인가(W.항목.length >= 5, `${W.항목.length}가지`);
  }
});
시험('항목마다 키·이름·값·요건이 있다 (화면이 그대로 보여 준다)', () => {
  for (const W of [보금우대, 디딤우대]) {
    for (const r of W.항목) {
      참인가(!!r.키 && !!r.이름, JSON.stringify(r));
      참인가(typeof r.값 === 'number' && r.값 > 0, `${r.이름} 값 ${r.값}`);
      참인가(!!r.요건 && r.요건.length > 5, `${r.이름} 요건이 없다`);
    }
  }
});
시험('키가 겹치지 않는다', () => {
  for (const W of [보금우대, 디딤우대]) {
    같나(new Set(W.항목.map((r) => r.키)).size, W.항목.length);
  }
});

묶음('우대금리 — 켜고 끄기');
시험('아무 조건도 없으면 공시금리 그대로', () => {
  const g = 보금자리론(S(맨바탕));
  같나(g.실제깎음, 0);
  가까운가(g.금리, g.공시금리, 0.001);
});
시험('신혼이면 보금자리론이 0.30%p 깎인다', () => {
  const g = 보금자리론(S({ ...맨바탕, 혼인: '신혼' }));
  가까운가(g.실제깎음, 0.30, 0.001);
});
시험('고른 조건 하나를 켜면 그만큼 깎인다 (한부모 0.70%p)', () => {
  const g = 보금자리론(S({ ...맨바탕, 우대한부모: true }));
  가까운가(g.실제깎음, 0.70, 0.001);
});

묶음('이미 답한 것으로 저절로 켜지는 조건은 스위치가 듣지 않는다');
// ⚠ 화면에서 두 번 묻지 않기 위해 자동으로 켠다. 그런데 `rules.js` 에 `자동: true` 를 빠뜨리면
//   화면에는 스위치가 생기는데 눌러도 아무 일이 없다 — 실제로 청약저축에서 그랬다.
for (const W of [{ 이름: '보금자리론', 표: 보금우대, 셈: 보금자리론 }, { 이름: '디딤돌', 표: 디딤우대, 셈: 디딤돌 }]) {
  for (const 항 of W.표.항목.filter((r) => r.자동)) {
    시험(`${W.이름} — 「${항.이름}」 은 스위치로 켜지지 않는다`, () => {
      const 전 = W.셈(S(맨바탕)).실제깎음;
      const 후 = W.셈(S({ ...맨바탕, [`우대${항.키}`]: true })).실제깎음;
      같나(후, 전);
    });
  }
  for (const 항 of W.표.항목.filter((r) => !r.자동)) {
    시험(`${W.이름} — 「${항.이름}」 은 스위치로 켜진다`, () => {
      const 전 = W.셈(S(맨바탕)).실제깎음;
      const 후 = W.셈(S({ ...맨바탕, [`우대${항.키}`]: true })).실제깎음;
      참인가(후 > 전, `${전} → ${후} — 눌러도 아무 일이 없다`);
    });
  }
}

묶음('함께 받을 수 없는 것');
시험('자녀 2명과 3명을 동시에 세지 않는다', () => {
  const 둘 = 보금자리론(S({ ...맨바탕, 자녀수: 2 }));
  const 셋 = 보금자리론(S({ ...맨바탕, 자녀수: 3 }));
  가까운가(둘.실제깎음, 0.50, 0.001);
  가까운가(셋.실제깎음, 0.70, 0.001);   // 0.5 + 0.7 이 아니라 0.7
});
시험('보금자리론 신생아와 신혼은 큰 쪽 하나만 (0.30, 0.20+0.30 이 아니다)', () => {
  const g = 보금자리론(S({ ...맨바탕, 혼인: '신혼', 우대신생아: true }));
  가까운가(g.실제깎음, 0.30, 0.001);
  거짓인가(g.우대.켜진것.some((r) => r.키 === '신생아'));
});
시험('신생아만 있으면 신생아가 들어간다', () => {
  const g = 보금자리론(S({ ...맨바탕, 우대신생아: true }));
  가까운가(g.실제깎음, 0.20, 0.001);
});

묶음('상한');
시험('다 더해도 상한까지만 깎인다', () => {
  const g = 보금자리론(S({
    ...맨바탕, 혼인: '신혼', 자녀수: 3, 우대한부모: true, 우대장애인: true, 우대다문화: true,
  }));
  참인가(g.우대.합 > 보금우대.상한, `합 ${g.우대.합}`);
  가까운가(g.우대.깎은값, 보금우대.상한, 0.001);
  가까운가(g.실제깎음, 보금우대.상한, 0.001);
  참인가(g.우대.잘림 > 0, '잘린 양을 알려 줘야 화면이 까닭을 말할 수 있다');
});
시험('전자약정(아낌e)은 상한 밖이라 더 깎인다', () => {
  const 안씀 = 보금자리론(S({ ...맨바탕, 혼인: '신혼', 자녀수: 3, 우대한부모: true }));
  const 씀 = 보금자리론(S({ ...맨바탕, 혼인: '신혼', 자녀수: 3, 우대한부모: true, 우대아낌e: true }));
  가까운가(안씀.실제깎음, 보금우대.상한, 0.001);
  가까운가(씀.실제깎음, 보금우대.상한 + 보금우대.아낌e.값, 0.001);
});
시험('디딤돌은 우대를 다 받아도 하한 아래로 안 내려간다', () => {
  const 몰아서 = {
    ...맨바탕, 내소득: 2000, 혼인: '신혼', 생애최초: true, 자녀수: 3, 청약잔액: 1000,
    우대장애인: true, 우대다문화: true, 우대전자계약: true,
  };
  const g = 디딤돌(S(몰아서));
  참인가(g.금리 >= 디딤우대.하한금리 - 0.001, `${g.금리} < 하한 ${디딤우대.하한금리}`);
});

묶음('★ 우대금리는 한도까지 바꾼다');
시험('DTI 가 묶고 있으면 우대를 받을수록 한도가 는다', () => {
  // 소득이 낮고 집값이 커서 DTI 가 묶는 상황을 일부러 만든다
  const 바탕 = { ...맨바탕, 매매가: 50000, 내소득: 3000 };
  const 전 = 보금자리론(S(바탕));
  const 후 = 보금자리론(S({ ...바탕, 우대한부모: true }));
  같나(전.묶은것[0], 'DTI 한도');
  참인가(후.한도 > 전.한도, `${Math.round(전.한도)} → ${Math.round(후.한도)} — 금리를 깎았는데 한도가 그대로다`);
});
시험('LTV 가 묶고 있으면 우대를 받아도 한도는 그대로다', () => {
  const 바탕 = { ...맨바탕, 매매가: 30000, 내소득: 6000 };
  const 전 = 보금자리론(S(바탕));
  const 후 = 보금자리론(S({ ...바탕, 우대한부모: true }));
  참인가(전.한도 <= 후.한도, '한도가 줄어들 수는 없다');
  // 한도가 그대로여도 **매달 갚는 돈은 줄어야** 한다 — 그게 우대금리의 본래 효과다
  const 달 = (g) => 월상환액(g.한도, g.금리, g.만기);
  참인가(달(후) < 달(전), `${Math.round(달(전))} → ${Math.round(달(후))}`);
});
시험('DTI 심사 금리가 우대 뒤 금리와 같다 (rules 의 dti반영 = true)', () => {
  const g = 보금자리론(S({ ...맨바탕, 우대한부모: true }));
  가까운가(g.심사금리, g.금리, 0.001);
});

묶음('우대셈 자체');
시험('표가 없으면 0 을 돌려준다 (터지지 않는다)', () => {
  const r = 우대셈(S({}), null);
  같나(r.총깎음, 0);
  같나(r.켜진것.length, 0);
});
시험('전부 목록에는 꺼진 것도 들어 있다 (화면이 안 켜진 까닭을 보여 준다)', () => {
  const r = 우대셈(S(맨바탕), 보금우대);
  같나(r.전부.length, 보금우대.항목.length);
  참인가(r.전부.every((x) => typeof x.켜짐 === 'boolean'));
});
