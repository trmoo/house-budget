/** 인쇄용 문서 한 장을 통째로 만든다 */
export function 인쇄문서(s) {
  const c = 계산(s);
  const 최대 = 최대매수가(s);
  return h('div', { id: 'print-root' },
    h('header', { class: 'p-head' },
      h('h1', {}, '내 집 예산 계산기'),
      h('p', {}, `계산일 ${오늘()} · 규정 기준일 ${기준일}`)),
    결론(s, c, 최대),
    넣은값(s, c),
    세갈래(c),
    우대금리칸(c),
    부대비용칸(s, c),
    필요현금칸(c),
    민감도칸(s),
    챙길것(s, c),
    꼬리());
}

/**
 * PDF 로 저장한다.
 * ⚠ 브라우저 인쇄창에서 **대상을 「PDF로 저장」** 으로 골라야 파일이 된다(기본이 프린터일 수 있다).
 *   파일 이름은 문서 제목에서 오므로 인쇄하는 동안만 제목을 바꾼다.
 */
export function 저장하기(s) {
  const 옛제목 = document.title;
  const 옛것 = document.getElementById('print-root');
  if (옛것) 옛것.remove();

  const 문서 = 인쇄문서(s);
  document.body.appendChild(문서);
  document.body.classList.add('printing');
  document.title = 파일이름();

  const 치우기 = () => {
    document.body.classList.remove('printing');
    document.title = 옛제목;
    const 남은것 = document.getElementById('print-root');
    if (남은것) 남은것.remove();
  };

  // 인쇄창이 닫히면 치운다. 알림이 안 오는 브라우저를 위해 시간제한도 둔다.
  let 끝남 = false;
  const 한번만 = () => { if (!끝남) { 끝남 = true; 치우기(); } };
  window.addEventListener('afterprint', 한번만, { once: true });
  setTimeout(한번만, 60000);

  window.print();
}
