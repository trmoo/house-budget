// 계산 과정과 결과를 한 장짜리 문서로 만들어 **PDF 로 저장**한다.
//
// ★ 왜 라이브러리를 안 쓰나 — 이 앱은 바깥 자원이 0개다(교실·사무실 인터넷이 끊겨도 열려야 한다).
//   jsPDF 같은 것을 넣으면 그 원칙이 깨지고 빌드본이 몇 배로 커진다.
//   그래서 **브라우저의 「인쇄 → PDF로 저장」** 을 쓴다. 크롬·엣지·사파리 모두에 들어 있다.
// ★ 저장되는 파일 이름은 **문서 제목(`document.title`)** 에서 온다.
//   그래서 인쇄하는 동안만 제목을 「내집예산계산기_2026-10-10」 으로 바꿨다가 되돌린다.
// ⚠ 화면에 있는 탭을 그대로 인쇄하지 않는다 — 접어 둔 상자가 접힌 채로 나가고,
//   지금 보고 있는 탭만 나간다. 그래서 **인쇄용 문서를 따로 짓는다.**

