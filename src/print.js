/** 계산한 날 — 파일 이름에 들어간다 */
export function 오늘() {
  const d = new Date();
  const 두자리 = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${두자리(d.getMonth() + 1)}-${두자리(d.getDate())}`;
}

/** 저장될 파일 이름 (확장자는 브라우저가 붙인다) */
export function 파일이름() {
  return `내집예산계산기_${오늘()}`;
}

function 묶음(제목, ...내용) {
  return h('section', { class: 'p-sec' }, h('h2', {}, 제목), ...내용);
}

function 쪽지(...글) {
  return h('p', { class: 'p-note' }, ...글);
}

function 두줄(이름, 값, 뒷말) {
  return h('div', { class: 'p-row' },
    h('span', { class: 'p-row-n' }, 이름),
    h('span', { class: 'p-row-v' }, h('b', {}, 값)),
    뒷말 ? h('span', { class: 'p-row-s' }, 뒷말) : null);
}

