// ② 집·지역 — 살 집, 지역, 내 조건, 대출 조건

import { h, 카드, 상자, 줄, 칸, 고르기, 스위치, 수입력, 돈입력, 접이, 비우기 } from '../lib/ui.js';
import { 상태, 넣기, 넣고그리기, 요약갱신, 다시그리기 } from '../lib/store.js';
import { 돈, 억짧게, 퍼센트 } from '../lib/fmt.js';
import { 담보가치, 서민실수요, 지역상한, 방공제금액 } from '../engine/loan.js';
import { 지역표, dsr as DSR, 서민실수요요건, 부대비용 } from '../rules.js';

const 방공제표 = 부대비용.방공제;

function 돈칸(이름, 열쇠, 도움말, 단위 = '만원') {
  return 칸(이름, 도움말, 돈입력({
    값: 상태[열쇠], 단위, id: `in-${열쇠}`,
    onInput: (v) => { 넣기(열쇠, v); 요약갱신(); },
    onChange: (v) => { 넣기(열쇠, v); 다시그리기(); },
  }));
}

export function 그리기(바탕) {
  const s = 상태;
  const 지 = 지역표[s.지역] || 지역표.규제;
  const 담보 = 담보가치(s);
  const 서민 = 서민실수요(s);
  const 상한 = 지역상한(s.지역, 담보);
  const 스트레스 = 지.스트레스 * (DSR.스트레스비율[s.금리유형] ?? 1);

  비우기(바탕);
  바탕.appendChild(h('div', {},

    /* ───── 살 집 ───── */
    카드('🏠 살 집',
      h('div', { class: 'grid2' },
        돈칸('매매가', '매매가', '실제로 사기로 한 값'),
        돈칸('KB시세 일반가', 'kb시세', '모르면 0 — 매매가와 같다고 봅니다')),
      h('div', { class: 'grid2' },
        칸('전용면적', '85㎡ 를 넘으면 취득세에 농어촌특별세 0.2% 가 붙습니다', 수입력({
          값: s.전용면적, 단위: '㎡', id: 'in-전용면적',
          onInput: (v) => { 넣기('전용면적', v); 요약갱신(); },
          onChange: (v) => { 넣기('전용면적', v); 다시그리기(); },
        })),
        칸('집 종류', '정책대출은 아파트가 아니면 LTV 가 낮습니다',
          고르기({
            항목들: [{ 값: true, 글자: '아파트' }, { 값: false, 글자: '아파트 아님' }],
            값: !!s.아파트, 칸수: 2, onPick: (v) => 넣고그리기('아파트', v),
          }))),
      h('div', { class: 'grid2' },
        칸('공시가격 (아는 경우만)', '0 이면 매매가의 69% 로 어림합니다. 국민주택채권 값을 셈하는 데 씁니다.', 돈입력({
          값: s.공시가격, 단위: '만원', id: 'in-공시가격',
          onInput: (v) => { 넣기('공시가격', v); 요약갱신(); },
          onChange: (v) => { 넣기('공시가격', v); 다시그리기(); },
        })),
        칸('특별시·광역시인가', '국민주택채권 매입률이 갈립니다', 고르기({
          항목들: [{ 값: true, 글자: '특별시·광역시' }, { 값: false, 글자: '그 밖' }],
          값: !!s.광역시, 칸수: 2, onPick: (v) => 넣고그리기('광역시', v),
        }))),
      줄('담보로 인정되는 값', h('b', {}, 돈(담보)),
        (Number(s.kb시세) || 0) > 0 && 담보 < s.매매가 ? '(KB시세가 낮아 그쪽으로)' : null),
      상자('info',
        '은행은 ', h('b', {}, '매매가와 시세 중 낮은 쪽'), '을 담보로 봅니다. ',
        'KB시세는 ', h('b', {}, 'KB부동산 → 시세 → 일반가'), ' 에서 확인하세요. ',
        '보금자리론은 매매가·시세·감정가 ', h('b', {}, '어느 하나라도'), ' 6억원을 넘으면 아예 안 됩니다.')),

    /* ───── 지역 ───── */
    카드('📍 지역',
      고르기({
        항목들: [
          { 값: '규제', 글자: '규제지역', 설명: '서울 전역·경기 15곳' },
          { 값: '수도권', 글자: '수도권 비규제', 설명: '인천·경기 나머지' },
          { 값: '지방', 글자: '지방', 설명: '수도권 밖' },
        ],
        값: s.지역, 칸수: 3, onPick: (v) => 넣고그리기('지역', v),
      }),
      h('div', { class: 'note note-info' },
        h('b', {}, `${지.이름} 규정 `), h('br'),
        `· LTV — 무주택 ${Math.round(지.ltv.무주택 * 100)}% · 생애최초 ${Math.round(지.ltv.생애최초 * 100)}%`
        + (s.지역 === '규제' ? ` · 서민·실수요자 ${Math.round(지.ltv.서민실수요 * 100)}%` : ''), h('br'),
        `· 스트레스 금리 — 기본 ${퍼센트(지.스트레스 * 100)}p`
        + (s.지역 === '지방' ? ` (2단계 유예, ${DSR.지방유예만료} 까지)` : ''), h('br'),
        `· 주담대 상한 — ${지.상한 ? '시가 15억 이하 6억 · 15~25억 4억 · 25억 초과 2억' : '없음'}`, h('br'),
        `· 만기 — ${지.최장만기 ? `최장 ${지.최장만기}년` : '제한 없음'}`,
        지.전입의무개월 ? h('span', {}, h('br'), `· 대출을 받으면 ${지.전입의무개월}개월 안에 전입해야 합니다`) : null,
        지.실거주의무 ? h('span', {}, h('br'), `· ${지.실거주의무}`) : null),
      접이('🗺 규제지역은 어디인가', h('p', {}, 지역표.규제.설명),
        h('p', {}, h('small', {}, '2025-10-16 에 서울 전역과 경기 12곳이, 2026-07-01 에 화성 동탄·용인 기흥·구리가 더해졌습니다. 지정은 바뀌니 계약 전에 국토교통부 실거래가공개시스템에서 주소로 확인하세요.')))),

    /* ───── 내 조건 ───── */
    카드('👤 내 조건',
      칸('지금 집이 몇 채 있나요', null, 고르기({
        항목들: [
          { 값: 0, 글자: '무주택' },
          { 값: 1, 글자: '1주택' },
          { 값: 2, 글자: '2주택 이상' },
        ],
        값: Number(s.주택수) || 0, 칸수: 3, onPick: (v) => 넣고그리기('주택수', v),
      })),
      Number(s.주택수) === 1 ? 스위치({
        켜짐: s.처분조건, 글자: '기존 집을 기한 안에 팔기로 하고 받는다',
        설명: '수도권·규제지역에서 1주택자가 집을 더 살 때는 이 조건이어야 주담대가 나옵니다(6개월 안에 처분).',
        onToggle: (v) => 넣고그리기('처분조건', v),
      }) : null,
      스위치({
        켜짐: s.생애최초, 글자: '생애최초로 집을 산다',
        설명: '부부 둘 다 집을 가진 적이 없어야 합니다. 규제지역에서는 이 하나로 LTV 가 40% ↔ 70% 로 갈립니다.',
        onToggle: (v) => 넣고그리기('생애최초', v),
      }),
      h('div', { class: 'grid2' },
        칸('혼인 상태', '정책대출 소득 상한이 달라집니다', 고르기({
          항목들: [
            { 값: '미혼', 글자: '미혼' },
            { 값: '신혼', 글자: '신혼(7년 이내)' },
            { 값: '그외', 글자: '그 외' },
          ],
          값: s.혼인, 칸수: 3, onPick: (v) => 넣고그리기('혼인', v),
        })),
        칸('미성년 자녀 수', '정책대출 소득·한도 우대', 수입력({
          값: s.자녀수, 단위: '명', id: 'in-자녀수',
          onInput: (v) => { 넣기('자녀수', v); 요약갱신(); },
          onChange: (v) => { 넣기('자녀수', Math.max(0, Math.round(v))); 다시그리기(); },
        }))),
      s.지역 === '규제' && Number(s.주택수) === 0
        ? 상자(서민.해당 ? 'good' : 'info',
          h('b', {}, `서민·실수요자 우대(LTV ${Math.round(지.ltv.서민실수요 * 100)}%) ${서민.해당 ? '해당' : '미해당'} `),
          h('br'),
          서민.조건.map((c) => h('span', {}, `${c.통과 ? '✓' : '✗'} ${c.글}${c.값 ? ` (${c.값})` : ''}`, h('br'))),
          h('small', {}, 서민실수요요건.불확실))
        : null),

    /* ───── 대출 조건 ───── */
    카드('🏦 대출 조건',
      h('div', { class: 'grid2' },
        칸('실제 대출 금리', '은행에서 알아본 금리', 수입력({
          값: s.금리, 단위: '%', id: 'in-금리',
          onInput: (v) => { 넣기('금리', v); 요약갱신(); },
          onChange: (v) => { 넣기('금리', v); 다시그리기(); },
        })),
        칸('대출 기간', 지.최장만기 ? `${지.이름}은 최장 ${지.최장만기}년` : '보통 30년', 수입력({
          값: s.기간, 단위: '년', id: 'in-기간',
          onInput: (v) => { 넣기('기간', v); 요약갱신(); },
          onChange: (v) => { 넣기('기간', Math.max(1, Math.round(v))); 다시그리기(); },
        }))),
      칸('금리 유형', 'DSR 심사에 붙는 스트레스 금리가 유형마다 다릅니다', 고르기({
        항목들: [
          { 값: '변동', 글자: '변동형', 설명: '100% 붙음' },
          { 값: '혼합', 글자: '혼합형', 설명: '80%' },
          { 값: '주기', 글자: '주기형', 설명: '40%' },
          { 값: '고정', 글자: '만기까지 고정', 설명: '안 붙음' },
        ],
        값: s.금리유형, 칸수: 4, onPick: (v) => 넣고그리기('금리유형', v),
      })),
      줄('DSR 심사에 쓰는 금리',
        h('b', {}, 퍼센트(Number(s.금리) + 스트레스 * 100)),
        `실제 ${퍼센트(s.금리)} + 스트레스 ${퍼센트(스트레스 * 100)}p`),
      s.금리유형 === '고정'
        ? 상자('good', '만기까지 금리가 고정되는 대출은 스트레스 금리를 붙이지 않습니다 — 그만큼 한도가 늘어납니다. 다만 ', h('b', {}, '「5년 고정 뒤 변동」은 혼합형'), ' 이라 80% 가 붙습니다.')
        : null,
      상한 != null
        ? 상자('warn', `${지.이름}에서 시가 ${억짧게(담보)} 집은 다른 조건이 아무리 좋아도 `, h('b', {}, `${억짧게(상한)}`), ' 이 주담대의 끝입니다.')
        : null),

    /* ───── 방공제 ───── */
    카드('🧯 방공제 (보증보험을 붙일 수 있나)',
      스위치({
        켜짐: s.방공제, 글자: '방공제가 빠진다 (보증보험 가입 불가)',
        설명: '보증보험(MCI·MCG)에 가입하면 한도에서 빼지 않습니다. 2026년 7월에 5대 은행이 모두 가입을 중단했다가 9~10월에 일부만 다시 열었으니, 은행에 꼭 물어보세요.',
        onToggle: (v) => 넣고그리기('방공제', v),
      }),
      s.방공제 ? 칸('집이 어디에 있나', '지역마다 빠지는 금액이 다릅니다', 고르기({
        항목들: 방공제표.map((r) => ({ 값: r.키, 글자: `${r.키} ${돈(r.값)}`, 설명: r.이름 })),
        값: s.방공제지역, 칸수: 2, onPick: (v) => 넣고그리기('방공제지역', v),
      })) : null,
      s.방공제 ? 상자('warn', '지금 설정으로는 대출 한도에서 ', h('b', {}, 돈(방공제금액(s))), ' 가 빠집니다.') : null,
      접이('🔎 방공제가 무엇인가', h('p', {}, '집이 경매로 넘어가면 소액 세입자가 은행보다 먼저 받아 가는 돈이 있습니다(주택임대차보호법). 은행은 그만큼 못 건질 수 있으니 미리 한도에서 뺍니다. 그 위험을 보험으로 넘기는 것이 MCI·MCG 입니다.'),
        h('p', {}, h('small', {}, '금액은 2023-02-21 개정 기준이고, 임대차계약일이 아니라 근저당 설정일이 기준입니다.'))))
  ));
}
