function 살림칸(이름, 열쇠, 도움말, 단위 = '만원') {
  return 칸(이름, 도움말, 돈입력({
    값: 상태[열쇠], 단위, id: `in-${열쇠}`,
    onInput: (v) => { 넣기(열쇠, v); 요약갱신(); },
    onChange: (v) => { 넣기(열쇠, v); 다시그리기(); },
  }));
}

export function 그리기(바탕) {
  const s = 상태;
  const c = 계산(s);
  const 최대 = 최대매수가(s);
  const 추천 = c.추천;
  const 지 = 지역표[s.지역] || 지역표.규제;

  비우기(바탕);
  const 통 = h('div', {});
  바탕.appendChild(통);

  /* ───── 큰 답 ───── */
  const 살수있나 = !!(추천 && 추천.살수있나);
  통.appendChild(h('div', { class: `big-answer ${살수있나 ? 'ok' : 'no'}` },
    h('div', { class: 'label' }, `${억짧게(s.매매가)} 집, 살 수 있을까`),
    h('div', { class: 'headline' }, 살수있나
      ? '살 수 있어요'
      : (추천 ? `${돈(Math.abs(추천.차이))} 모자라요`
        : (c.현금만.살수있나 ? '대출은 안 나오지만, 현금으로는 됩니다' : '지금 조건으로는 대출이 안 나옵니다'))),
    추천 ? h('div', { class: 'detail' },
      살수있나
        ? `${추천.이름}으로 ${돈(추천.대출)} 빌리고, 종잣돈이 ${돈(추천.차이)} 남습니다`
        : `${추천.이름}으로 ${돈(추천.대출)}까지 빌려도 현금이 ${돈(추천.필요현금)} 필요합니다`)
      : h('div', { class: 'detail' },
        `대출 없이 현금으로만 치르면 ${돈(c.현금만.필요현금)} 이 필요합니다 — `
        + (c.현금만.살수있나 ? `종잣돈이 ${돈(c.현금만.차이)} 남습니다` : `${돈(Math.abs(c.현금만.차이))} 모자랍니다`)),
    h('div', { class: 'detail', style: { marginTop: '8px', fontWeight: '700' } },
      `지금 종잣돈 ${돈(c.씨.합)}으로는 `,
      h('b', {}, `최대 ${돈(최대.값)}`),
      최대.넘침 ? ' 넘게까지 됩니다' : ' 짜리까지 됩니다')));

  if (최대.막힌까닭) 통.appendChild(카드(null, ...영원인설명(최대.막힌까닭)));
  통.appendChild(접이('「살 수 있는 값」은 어떻게 나온 값인가', ...셈하는법(c, 최대)));

  통.appendChild(h('div', { class: 'stats' },
    수칸('종잣돈', 돈(c.씨.합)),
    수칸('총 필요 현금', 추천 ? 돈(추천.필요현금) : '—', '집값 − 대출 + 비용 + 살림'),
    수칸('대출', 추천 ? 돈(추천.대출) : '—', 추천 ? `${추천.이름} · ${퍼센트(추천.금리)}` : null, true),
    수칸('매달 갚는 돈', 추천 ? 원(Math.round(추천.월상환원)) : '—', 추천 ? `${추천.만기}년 원리금균등` : null)));

  /* ───── 세 갈래 비교 ───── */
  통.appendChild(h('h2', { class: 'part' }, '어느 길로 빌릴까'));
  통.appendChild(카드(null,
    표(['', '한도', '금리', '매달', '필요 현금', ''],
      c.갈래들.map((g) => ({
        강조: 추천 && g.키 === 추천.키,
        칸: [
          h('span', {}, h('b', {}, g.이름), g.가능 ? null : h('small', {}, '받을 수 없음')),
          g.가능 ? 억짧게(g.한도) : '—',
          g.가능 ? 퍼센트(g.금리) : '—',
          g.가능 ? `${숫자(Math.round(g.월상환원 / 10000))}만원` : '—',
          g.가능 ? 억짧게(g.필요현금) : '—',
          g.가능 ? (g.살수있나 ? '○ 가능' : (g.한도0 ? '✗ 한도 0' : '△ 모자람')) : '✗',
        ],
      }))),
    추천 ? 상자('good', h('b', {}, `${추천.이름} `), 추천이유글(c)) : 상자('bad', '세 갈래 모두 막혀 있습니다. 아래에서 막힌 까닭을 보세요.'),
    ...c.갈래들.map((g) => 갈래상세(g))));

  /* ───── 무엇이 묶었나 ───── */
  if (추천 && 추천.가능) {
    통.appendChild(h('h2', { class: 'part' }, '무엇이 한도를 묶었나'));
    통.appendChild(카드(null,
      ...추천.묶은것.map((이름) => h('div', {},
        줄(이름, h('b', {}, 돈(추천.한도))),
        상자('info', 풀는법[이름] ? 굵게(풀는법[이름]) : 이름))),
      추천.경고 && 추천.경고.length ? 추천.경고.map((w) => 상자('warn', w)) : null));
  }

  /* ───── 부대비용 ───── */
  const 세 = c.세금.취득세;
  const 중개 = c.세금.중개;
  const 등기 = c.세금.등기;
  const 증여 = c.세금.증여;
  통.appendChild(h('h2', { class: 'part' }, '집값 말고 더 드는 돈'));
  통.appendChild(카드(null,
    줄('취득세·지방교육세·농특세', h('b', {}, 돈(세.합)), 세.설명),
    접이('🧾 취득세 셈한 과정',
      표(null, [
        ['본세', `${돈(세.본세)}`, `세율 ${(세.세율 * 100).toFixed(2).replace(/\.?0+$/, '')}%${세.중과율 ? ' (중과)' : ''}`],
        ['지방교육세', 돈(세.교육세), 세.중과율 ? '중과일 때는 0.4% 고정' : '취득세의 10분의 1'],
        ['농어촌특별세', 돈(세.농특세), 세.큰면적 ? `전용 ${s.전용면적}㎡ 라 ${(세.농특율 * 100).toFixed(1)}%` : '85㎡ 이하는 없음'],
        [세.감면이름 ? `${세.감면이름} 감면` : '감면', 세.감면 ? `− ${돈(세.감면)}` : '0원', 세.감면설명 || '해당 없음'],
      ]),
      세.중과사유 ? 상자('bad', 세.중과사유) : null,
      세.일시적2주택 ? 상자('warn', '일시적 2주택으로 보아 중과하지 않았습니다. ', h('b', {}, '기한 안에 기존 집을 팔지 못하면 중과세율로 다시 내야 합니다'), ' — 둘 다 조정대상지역이면 2년, 아니면 3년입니다(2026-10-01 이후 취득분 기준).') : null,
      상자('info', '취득세는 잔금 치른 날부터 ', h('b', {}, '60일 안에'), ' 신고·납부합니다. 과세표준에 중개보수는 들어가지 않습니다.')),
    줄('중개보수', h('b', {}, 돈(중개.합)), 중개.설명),
    줄('등기 비용', h('b', {}, 돈(등기.합)), '채권·인지세·법무사'),
    접이('📜 등기 비용 셈한 과정',
      표(null, 등기.줄.map((r) => [r.이름, 돈(r.값), h('small', {}, r.설명 || '')])),
      상자('info', h('b', {}, '집을 사는 등기에는 「등록면허세」가 따로 없습니다. '),
        '2011년에 취득세로 합쳐졌습니다. 실제로 드는 것은 국민주택채권을 사서 바로 팔 때의 손해(할인비)와 인지세·수수료·법무사 보수입니다. ',
        '채권 할인율은 그날 시세에 따라 달라지니 아래에서 고쳐 보세요.')),
    추천 && 추천.근저당 && 추천.근저당.합 > 0 ? h('div', {},
      줄('근저당 설정', h('b', {}, 돈(추천.근저당.합)), '채권 할인비 + 인지세 절반'),
      접이('🏦 근저당은 왜 이것뿐인가', 상자('info', 추천.근저당.메모))) : null,
    증여.셈함 ? 줄('증여세', h('b', {}, 돈(증여.세액)), 증여.설명) : null,
    h('div', { class: 'row', style: { borderTop: '1.5px solid #ccc', marginTop: '6px', paddingTop: '10px' } },
      h('span', { class: 'row-name' }, h('b', {}, '부대비용 합계')),
      h('span', { class: 'row-val' }, h('b', {}, 돈(c.세금.합 + (추천 ? 추천.근저당.합 : 0)))))));

  /* ───── 필요 현금 ───── */
  통.appendChild(h('h2', { class: 'part' }, '통장에 실제로 있어야 할 돈'));
  통.appendChild(카드(null,
    표(['항목', '금액', '무엇인가'], [
      ['집값 − 대출', 돈(추천 ? Math.max(0, c.가격 - 추천.대출) : c.가격), '내가 바로 내야 하는 돈'],
      ['부대비용', 돈(c.세금.합 + (추천 ? 추천.근저당.합 : 0)), '세금·중개·등기'],
      ...c.여윳돈줄.map((r) => [r.이름, 돈(r.값), h('small', {}, r.설명 || '')]),
      { 강조: true, 칸: [h('b', {}, '합계'), h('b', {}, 돈(추천 ? 추천.필요현금 : 0)), ''] },
      ['종잣돈', 돈(c.씨.합), ''],
      {
        강조: true,
        칸: [
          h('b', {}, 추천 && 추천.차이 >= 0 ? '남는 돈' : '모자란 돈'),
          h('b', {}, 돈(Math.abs(추천 ? 추천.차이 : 0))),
          '',
        ],
      },
    ]),
    h('div', { class: 'grid2', style: { marginTop: '12px' } },
      살림칸('월 생활비', '월생활비', '비상금을 셈하는 데 쓴다'),
      칸('비상금은 몇 개월치로', '집을 사면 통장이 빈다 — 6개월치를 권한다', 수입력({
        값: s.비상금개월, 단위: '개월', id: 'in-비상금개월',
        onInput: (v) => { 넣기('비상금개월', v); 요약갱신(); },
        onChange: (v) => { 넣기('비상금개월', Math.max(0, Math.round(v))); 다시그리기(); },
      }))),
    h('div', { class: 'grid2' },
      살림칸('가전·가구', '가전가구', '에어컨·냉장고·침대 등'),
      살림칸('이사비·기타', '이사비', '이사·입주청소')),
    h('div', { class: 'grid2' },
      살림칸('수리·인테리어', '수리비', '구축이면 도배·장판·욕실만 해도 적지 않습니다'),
      h('div', {})),
    칸('국민주택채권 할인율', '2026년 10월은 15.8% 쯤입니다. 잔금 치르는 날 값은 주택도시기금 포털 「고객부담금조회」에서 확인하세요.', 수입력({
      값: s.채권할인율, 단위: '%', id: 'in-채권할인율',
      onInput: (v) => { 넣기('채권할인율', v); 요약갱신(); },
      onChange: (v) => { 넣기('채권할인율', v); 다시그리기(); },
    })),
    스위치({
      켜짐: s.법무사직접, 글자: '법무사 없이 직접 등기한다',
      설명: '셀프 등기를 하면 보수가 들지 않습니다(대신 하루가 듭니다).',
      onToggle: (v) => 넣고그리기('법무사직접', v),
    }),
    !s.법무사직접 ? 스위치({
      켜짐: s.법무사따로, 글자: '법무사 보수를 직접 적는다',
      설명: `기본은 법무사협회 기준 상한(지금 ${돈(Math.round(c.세금.등기.상한))}, 부가세 포함)으로 셈합니다. 실제로는 깎아서 집값의 0.1% 안팎으로 하는 경우가 많습니다.`,
      onToggle: (v) => 넣고그리기('법무사따로', v),
    }) : null,
    !s.법무사직접 && s.법무사따로 ? 살림칸('법무사 보수', '법무사보수', '부가세까지 포함한 금액') : null));

  /* ───── 매달 갚는 돈 ───── */
  if (추천 && 추천.가능) {
    const 월소득원 = ((Number(s.내소득) || 0) + (Number(s.배우자소득) || 0)) * 10000 / 12;
    const 실수령 = (Number(s.내실수령) || 0) + (Number(s.배우자실수령) || 0);
    통.appendChild(h('h2', { class: 'part' }, '매달 갚는 돈'));
    통.appendChild(카드(null,
      h('div', { class: 'stats' },
        수칸('월 상환액', 원(Math.round(추천.월상환원)), `${추천.만기}년 · ${퍼센트(추천.금리)}`, true),
        수칸('세전 소득 대비', 월소득원 > 0 ? 퍼센트((추천.월상환원 / 월소득원) * 100, 1) : '—', '부부합산 세전'),
        수칸('실수령 대비', 실수령 > 0 ? 퍼센트((추천.월상환원 / 실수령) * 100, 1) : '적어 주세요', '두 사람 합계 · 체감은 이쪽'),
        수칸(`${추천.만기}년 동안 낼 이자`, 돈(추천.총이자 / 10000), '원금 빼고')),
      실수령 === 0 ? 상자('info', '「내 상황」 탭에 월 실수령액을 적으면 체감 부담률을 함께 보여 줍니다. 세전 기준은 실제보다 가볍게 보입니다.') : null,
      추천.월상환원 > 월소득원 * 0.4 ? 상자('warn', '세전 소득의 40%를 넘습니다. 규정은 통과해도 생활이 빡빡해집니다.') : null));
  }

  /* ───── 민감도 ───── */
  const m = 민감도(s);
  통.appendChild(h('h2', { class: 'part' }, '무엇을 바꾸면 얼마나 달라지나'));
  통.appendChild(카드(null,
    표(['바꿔 보면', '살 수 있는 값', '은행 한도'],
      m.줄.map((r) => [
        h('span', {}, r.이름, r.설명 ? h('small', {}, r.설명) : null),
        h('span', {}, 억짧게(r.최대), h('small', {}, 차글(r.최대차))),
        h('span', {}, 억짧게(r.은행), h('small', {}, 차글(r.은행차))),
      ])),
    상자('info', `지금 바탕은 「${m.바탕.추천이름}」 기준입니다. 정책대출은 금리가 따로 정해져 있어서, 위에 적은 금리를 바꿔도 정책대출 한도는 움직이지 않습니다.`)));

  /* ───── 놓치면 안 되는 것 ───── */
  통.appendChild(h('h2', { class: 'part' }, '놓치면 큰일 나는 것'));
  통.appendChild(카드(null, ...해야할것(s, c, 지).map((g) => 상자('warn', g))));
}

function 차글(차) {
  if (Math.round(차) === 0) return ' 그대로';
  return ` ${차 > 0 ? '+' : '−'}${돈(Math.abs(차))}`;
}

function 추천이유글(c) {
  return `${c.추천이유} 한도 ${돈(c.추천.한도)} · 금리 ${퍼센트(c.추천.금리)} · 매달 ${원(Math.round(c.추천.월상환원))}.`;
}

function 갈래상세(g) {
  return 접이(`${g.살수있나 ? '○' : g.가능 ? '△' : '✗'} ${g.이름} — 자세히`,
    !g.가능 && g.금지이유 ? 상자('bad', 굵게(g.금지이유)) : null,
    g.자격 ? 표(['자격', '', ''], g.자격.map((c) => [
      c.통과 === null ? '?' : (c.통과 ? '✓' : '✗'),
      c.글,
      h('small', {}, c.값 || c.쪽지 || ''),
    ])) : null,
    g.가능 ? 표(['한도를 정하는 것', '금액', '어떻게'], g.항목.map((a) => ({
      강조: Math.abs(a.값 - g.한도) < 1,
      칸: [a.이름, 돈(a.값), h('small', {}, a.설명 || '')],
    }))) : null,
    g.가능 ? 줄('빌리는 금리', 퍼센트(g.금리), g.금리설명) : null,
    g.메모 ? g.메모.map((t) => 상자('info', 굵게(t))) : null,
    g.시행되면 ? 상자('warn',
      h('b', {}, '곧 바뀔 수 있습니다 — '),
      `지금은 부부합산 ${돈(g.합산)} 이라 안 되지만, 8·13 대책대로 시행되면 `,
      h('b', {}, `적게 버는 쪽(${돈(g.적은쪽)})`),
      ` 기준으로 받을 수 있게 됩니다. `,
      굵게(g.신혼1인.시행)) : null,
    g.신혼1인 && g.한사람기준 !== undefined ? 상자(g.한사람기준 ? 'good' : 'info',
      h('b', {}, `${g.신혼1인.날짜}부터 — `), 굵게(g.신혼1인.내용), h('br'), h('small', {}, g.신혼1인.주의)) : null);
}

/** 계산 결과에 따라 챙겨야 하는 일들 */
function 해야할것(s, c, 지) {
  const 목록 = [];
  if (지.전입의무개월) {
    목록.push(`${지.이름}에서 주택담보대출을 받으면 ${지.전입의무개월}개월 안에 전입해야 합니다. 못 하면 대출을 바로 갚아야 합니다.`);
  }
  if (지.실거주의무) 목록.push(지.실거주의무);
  if (Number(s.주택수) === 1 && s.처분조건) {
    목록.push('기존 집을 기한 안에 팔아야 합니다 — 은행 대출은 6개월, 보금자리론은 3년, 취득세 중과를 피하려면 2~3년입니다. 기한이 서로 달라서 가장 짧은 것에 맞춰야 합니다.');
  }
  목록.push('취득세는 잔금 치른 날부터 60일 안에 신고·납부합니다.');
  if (s.지역 === '규제' || c.가격 >= 60000) {
    목록.push('자금조달계획서를 내야 합니다 — 규제지역이면 금액과 상관없이, 아니면 6억원 이상일 때. 투기과열지구·토지거래허가구역이면 통장 잔액 같은 증빙까지 붙여야 합니다. 계약한 날부터 30일 안에 냅니다.');
  }
  if (c.세금.증여.셈함 && c.세금.증여.받은 > 0) {
    목록.push('부모님께 받은 돈은 증여받은 달의 말일부터 3개월 안에 신고해야 합니다. 세금이 0원이어도 신고해 두면 나중에 자금 출처를 밝히기 쉽습니다.');
  }
  if (c.세금.취득세.감면 > 0) {
    목록.push('생애최초 취득세 감면을 받으면 3년 안에 팔거나 증여하거나 임대하면 깎아 준 세금을 되돌려 냅니다.');
  }
  return 목록;
}

/**
 * 「살 수 있는 값」이 0 일 때 — 고장이 아니라 답이라는 것을 밝힌다.
 * ⚠ 0 만 보여 주면 쓰는 사람은 계산기가 고장 났다고 여긴다(실제로 그런 물음을 받았다).
 */
function 영원인설명(왜) {
  if (왜.종류 === '종잣돈없음') {
    return [
      상자('bad', h('b', {}, '지금 손에 있는 돈이 0원입니다. '),
        '「① 내 상황」 탭에 예금·주식·전세보증금·부모님 지원을 적어 주세요. 종잣돈이 없으면 어떤 집도 살 수 없으니 0원으로 나옵니다.'),
      상자('info', '참고로 집값을 0원으로 놓아도 ', h('b', {}, 돈(왜.바닥)),
        ` 은 듭니다 — 살림 준비 ${돈(왜.여윳돈)}(비상금·가전·이사·수리) + 등기·수수료 ${돈(왜.부대)}.`),
    ];
  }
  if (왜.종류 === '기본비용초과') {
    return [
      상자('bad', h('b', {}, '집값을 빼고 드는 돈부터 모자랍니다. '),
        `집값을 0원으로 놓아도 ${돈(왜.바닥)} 이 드는데(살림 준비 ${돈(왜.여윳돈)} + 등기·수수료 ${돈(왜.부대)}), `,
        `지금 종잣돈은 ${돈(왜.씨)} 입니다. 집값을 아무리 낮춰도 감당이 안 되니 0원으로 나옵니다.`),
      상자('info', 굵게('고치는 길은 둘입니다 — ① 종잣돈을 더 적거나(빠뜨린 돈이 없는지 보세요) ② 「살림 준비」 금액을 현실에 맞게 줄이세요. '
        + '가전·가구와 비상금은 기본값이 들어 있어서, 실제보다 크게 잡혀 있을 수 있습니다.')),
    ];
  }
  return [
    상자('bad', h('b', {}, '대출도 현금도 닿지 않습니다. '),
      `집값을 0원으로 놓아도 ${돈(왜.바닥)} 이 드는 조건에서, 종잣돈 ${돈(왜.씨)} 으로는 어떤 집값도 맞출 수 없었습니다.`),
    ...왜.금지.filter(Boolean).map((이유) => 상자('warn', 굵게(이유))),
  ];
}

