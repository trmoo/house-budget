import { h, 카드, 상자, 줄, 칸, 표, 돈입력, 수입력, 스위치, 접이, 비우기 } from '../lib/ui.js';
import { 상태, 넣기, 넣고그리기, 요약갱신, 다시그리기 } from '../lib/store.js';
import { 돈, 원, 숫자 } from '../lib/fmt.js';
import { 종잣돈 } from '../engine/cash.js';
import { 기존부채 } from '../engine/loan.js';
import { dsr as DSR } from '../rules.js';

/** 돈 칸 하나 만들기 — 치는 동안에는 요약만 갱신하고, 손을 떼면 다시 그린다 */
function 돈칸(이름, 열쇠, 도움말, 옵션 = {}) {
  return 칸(이름, 도움말, 돈입력({
    값: 상태[열쇠],
    id: `in-${열쇠}`,
    단위: 옵션.단위 || '만원',
    작게: 옵션.작게,
    onInput: (v) => { 넣기(열쇠, v); 요약갱신(); },
    onChange: (v) => { 넣기(열쇠, v); 다시그리기(); },
  }));
}

export function 그리기(바탕) {
  const s = 상태;
  const 씨 = 종잣돈(s);
  const 빚 = 기존부채(s);

  비우기(바탕);
  바탕.appendChild(h('div', {},

    /* ───── 종잣돈 ───── */
    카드('💰 지금 손에 있는 돈',
      h('div', { class: 'grid2' },
        돈칸('예금·적금·CMA', '예금', '바로 꺼낼 수 있는 돈'),
        돈칸('주식·펀드', '주식', '실제로 팔아서 집에 넣을 금액만')),
      h('div', { class: 'grid2' },
        돈칸('지금 사는 집 전세보증금', '전세보증금', '없으면 0'),
        돈칸('그 보증금에 낀 전세대출', '전세대출', '돌려줄 돈이니 뺀다')),
      돈칸('부모님 지원', '부모지원', '말로 한 약속이 아니라 날짜와 금액이 정해진 것만'),
      (Number(s.부모지원) || 0) > 0 ? h('div', {},
        스위치({
          켜짐: s.증여계산, 글자: '증여세를 셈해 본다',
          설명: '부모가 주는 돈은 증여다. 공제를 넘으면 세금을 내야 하니 쓸 수 있는 돈이 줄어든다.',
          onToggle: (v) => 넣고그리기('증여계산', v),
        }),
        s.증여계산 ? 스위치({
          켜짐: s.증여혼인공제, 글자: '혼인 공제(1억)를 쓸 수 있다',
          설명: '혼인신고 앞뒤 2년 안에 받는 돈이면 기본 공제와 별도로 1억원이 더 공제된다.',
          onToggle: (v) => 넣고그리기('증여혼인공제', v),
        }) : null) : null,
      줄('종잣돈 합계', h('b', {}, 돈(씨.합))),
      상자('info',
        '전세보증금은 ', h('b', {}, '잔금 날짜와 보증금 돌려받는 날짜가 맞아야'), ' 쓸 수 있습니다. ',
        '두 날이 어긋나면 그 사이를 메울 돈(또는 단기 대출)이 따로 필요합니다.')),

    /* ───── 소득 ───── */
    카드('💼 소득 (세전 연봉)',
      h('div', { class: 'grid2' },
        돈칸('내 연봉', '내소득', '원천징수영수증의 총급여 · 사업자는 소득금액증명원'),
        돈칸('배우자 연봉', '배우자소득', '없으면 0')),
      스위치({
        켜짐: s.부부공동, 글자: '은행 DSR 에 두 사람 소득을 합친다',
        설명: '은행 DSR 은 원칙적으로 돈을 빌리는 사람 본인 소득만 봅니다. 배우자 소득을 합치려면 공동차주로 들어가야 하고, 되는지는 은행마다 다릅니다. (디딤돌·보금자리론은 자격을 볼 때 언제나 부부합산입니다.)',
        onToggle: (v) => 넣고그리기('부부공동', v),
      }),
      칸('월 실수령액 (적어 두면 더 정확합니다)', '세금·4대보험을 뗀 실제 통장 입금액. 0 이면 세전 기준으로만 보여 줍니다.',
        돈입력({
          값: s.월실수령, 단위: '원', id: 'in-월실수령',
          onInput: (v) => { 넣기('월실수령', v); 요약갱신(); },
          onChange: (v) => { 넣기('월실수령', v); 다시그리기(); },
        }))),

    /* ───── 기존 부채 ───── */
    카드('🧾 이미 있는 빚',
      상자('warn',
        h('b', {}, '여기는 「실제로 내는 돈」이 아니라 「규정이 셈하는 방식」으로 넣습니다. '),
        '마이너스통장은 한 푼도 안 썼어도 ', h('b', {}, '한도 전액'), '이 들어가고, ',
        '신용대출도 실제 만기와 무관하게 ', h('b', {}, `${DSR.신용대출산정만기}년`), '에 나눠 셈합니다. ',
        '그래서 「월 이자만」 적는 계산기보다 한도가 훨씬 적게 나옵니다.'),
      h('div', { class: 'grid2' },
        돈칸('신용대출 잔액', '신용잔액', '남은 원금'),
        칸('신용대출 금리', ' ', 수입력({
          값: s.신용금리, 단위: '%', id: 'in-신용금리',
          onInput: (v) => { 넣기('신용금리', v); 요약갱신(); },
          onChange: (v) => { 넣기('신용금리', v); 다시그리기(); },
        }))),
      h('div', { class: 'grid2' },
        돈칸('마이너스통장 한도', '마통한도', '약정 한도 전체 (쓴 금액이 아니다)'),
        칸('마이너스통장 금리', ' ', 수입력({
          값: s.마통금리, 단위: '%', id: 'in-마통금리',
          onInput: (v) => { 넣기('마통금리', v); 요약갱신(); },
          onChange: (v) => { 넣기('마통금리', v); 다시그리기(); },
        }))),
      h('div', { class: 'grid2' },
        칸('다른 집의 주담대 월 상환액', '지금 다른 집에 대출이 걸려 있다면', 돈입력({
          값: s.기타주담월, 단위: '원', id: 'in-기타주담월',
          onInput: (v) => { 넣기('기타주담월', v); 요약갱신(); },
          onChange: (v) => { 넣기('기타주담월', v); 다시그리기(); },
        })),
        칸('학자금대출 월 상환액', '금융회사에 따라 DSR 에서 빠질 수도 있습니다', 돈입력({
          값: s.학자금월, 단위: '원', id: 'in-학자금월',
          onInput: (v) => { 넣기('학자금월', v); 요약갱신(); },
          onChange: (v) => { 넣기('학자금월', v); 다시그리기(); },
        }))),
      (Number(s.학자금월) || 0) > 0 ? 스위치({
        켜짐: s.학자금포함, 글자: '학자금대출을 DSR 에 넣는다',
        설명: '넣는 쪽이 보수적입니다. 은행에 물어보고 끄면 한도가 조금 늘어납니다.',
        onToggle: (v) => 넣고그리기('학자금포함', v),
      }) : null,
      칸('자동차 할부·리스 월 납입액', 'DSR 에서는 빠집니다. 생활비로만 들어갑니다.', 돈입력({
        값: s.할부월, 단위: '원', id: 'in-할부월',
        onInput: (v) => { 넣기('할부월', v); 요약갱신(); },
        onChange: (v) => { 넣기('할부월', v); 다시그리기(); },
      })),

      빚.줄.length > 0 || 빚.제외줄.length > 0
        ? 접이('🔎 DSR 에 얼마로 들어가나 (셈한 과정)',
          빚.줄.length > 0
            ? 표(['빚', '연 상환액(셈)', '어떻게 셈했나'],
              빚.줄.map((r) => [r.이름, 돈(r.연), h('small', {}, r.설명.replace(/\*\*/g, ''))])
                .concat([[h('b', {}, '합계'), h('b', {}, `${돈(빚.연)} / 년`), h('small', {}, `월 ${원(Math.round(빚.월원))}`)]]))
            : h('p', {}, '아직 넣은 빚이 없습니다.'),
          빚.제외줄.length > 0
            ? 상자('info', 'DSR 에서 빠진 것: ',
              빚.제외줄.map((r) => `${r.이름}(월 ${숫자(r.월원)}원)`).join(' · '))
            : null)
        : null)
  ));
}
