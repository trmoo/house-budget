/** 부모님께 받는 돈 — 얼마까지 세금이 없는지 자세히 */
function 증여설명(s) {
  const Z = 세금.증여세;
  const 최대 = Z.공제.성년자녀10년 + Z.공제.혼인출산합산;
  const z = 증여세(s);
  return 접이('🎀 부모님께 받는 돈 — 얼마까지 세금이 없나',
    표(['받는 사람 한 명 기준', '공제되는 금액'], [
      ['기본 — 성년 자녀가 직계존속에게 (10년 합산)', 돈(Z.공제.성년자녀10년)],
      ['혼인 — 혼인신고일 앞뒤 2년 안', 돈(Z.공제.혼인출산합산)],
      ['출산 — 낳거나 입양하고 2년 안', '혼인 공제와 합쳐서'],
      { 강조: true, 칸: ['한 사람이 세금 없이 받을 수 있는 최대', 돈(최대)] },
    ]),
    ...Z.메모.map((t) => 상자(t.startsWith('⚠') ? 'warn' : (t.startsWith('★') ? 'good' : 'info'), 굵게(t))),
    표(['과세표준 (받은 돈 − 공제)', '세율', '누진공제'],
      Z.세율표.map(([상한, 율, 누진]) => [
        상한 === Infinity ? '30억원 초과' : `${돈(상한)} 이하`,
        `${Math.round(율 * 100)}%`,
        누진 ? 돈(누진) : '없음',
      ])),
    z.셈함
      ? 줄('지금 적은 금액으로는',
        h('b', {}, z.세액 > 0 ? `증여세 ${돈(z.세액)}` : '세금 없음'),
        z.설명)
      : null,
    상자('info', `혼인·출산 공제는 ${Z.적용시작} 적용됩니다. 신고는 ${Z.신고기한}.`));
}

