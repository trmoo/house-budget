export const 상태 = { ...기본 };

let 그리기 = null;
let 요약 = null;

/** main.js 가 화면을 다시 그리는 함수를 여기에 등록한다 */
export function 그리기등록(fn) { 그리기 = fn; }

/** 머리말 아래 요약 줄만 다시 쓰는 함수를 등록한다 */
export function 요약등록(fn) { 요약 = fn; }

/**
 * 요약 줄만 갱신한다.
 * ⚠ 숫자를 한 자 칠 때마다 화면을 통째로 다시 그리면, 쉼표가 끼어들어 커서가 엉킨다.
 *   그래서 글자를 치는 중에는 이것만 부르고, 손을 뗄 때(change) 전체를 다시 그린다.
 */
export function 요약갱신() { if (요약) 요약(); }

/** 값 하나를 바꾸고 저장한다 (화면은 다시 그리지 않는다) */
export function 넣기(키, 값) {
  상태[키] = 값;
  저장();
}

/** 값을 바꾸고 화면까지 다시 그린다 */
export function 넣고그리기(키, 값) {
  넣기(키, 값);
  다시그리기();
}

export function 저장() {
  try { localStorage.setItem(저장열쇠, JSON.stringify(상태)); } catch (e) { /* 사생활 보호 모드 등 */ }
}

export function 불러오기() {
  try {
    const 글 = localStorage.getItem(저장열쇠);
    if (!글) return;
    const o = JSON.parse(글);
    for (const k of Object.keys(기본)) {
      if (o[k] !== undefined && typeof o[k] === typeof 기본[k]) 상태[k] = o[k];
    }
    // 예전에 한 칸이던 월 실수령액을 두 칸으로 나눴다 — 적어 둔 값을 잃지 않게 옮긴다
    if (o.월실수령 && !o.내실수령) 상태.내실수령 = Number(o.월실수령) || 0;
  } catch (e) { /* 깨진 값은 무시하고 기본값으로 */ }
}

export function 지우기() {
  try { localStorage.removeItem(저장열쇠); } catch (e) { /* 무시 */ }
  Object.assign(상태, 기본);
}

/**
 * 화면을 다시 그리면서 스크롤 위치와 고치고 있던 칸을 지킨다.
 * ⚠ 다시 그릴 때 이것을 안 지키면, 숫자를 한 자 칠 때마다 화면 맨 위로 튄다.
 */
export function 다시그리기() {
  if (!그리기) return;
  const y = window.scrollY;
  const 그놈 = document.activeElement;
  const 아이디 = 그놈 && 그놈.id ? 그놈.id : null;
  const 커서 = 그놈 && 그놈.selectionStart != null ? 그놈.selectionStart : null;
  그리기();
  window.scrollTo(0, y);
  if (아이디) {
    const 새놈 = document.getElementById(아이디);
    if (새놈) {
      새놈.focus({ preventScroll: true });
      if (커서 != null && 새놈.setSelectionRange) {
        try { 새놈.setSelectionRange(커서, 커서); } catch (e) { /* number 칸 등 */ }
      }
    }
  }
}

/** 담보로 잡히는 값: KB시세를 적었으면 매매가와 비교해 낮은 쪽 */
export function 담보가치(s = 상태) {
  const kb = Number(s.kb시세) || 0;
  return kb > 0 ? Math.min(s.매매가, kb) : s.매매가;
}

/** 소득 — 은행 DSR 은 원칙적으로 차주 본인 소득, 정책대출은 부부합산 */
export function 소득(s = 상태) {
  const 나 = Number(s.내소득) || 0;
  const 배 = Number(s.배우자소득) || 0;
  return { 본인: 나, 부부합산: 나 + 배 };
}
