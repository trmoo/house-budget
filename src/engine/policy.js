/**
 * DTI 에 들어가는 기존 빚. (만원/년)
 * DSR 과 다르다 — 주담대는 원리금을 다 보지만, 그 밖의 대출은 **이자만** 본다.
 */
export function 기존부채DTI(s) {
  const 줄 = [];
  const 신용 = Number(s.신용잔액) || 0;
  if (신용 > 0) 줄.push({ 이름: '신용대출 이자', 연: (신용 * (Number(s.신용금리) || 0)) / 100 });
  const 마통 = Number(s.마통한도) || 0;
  if (마통 > 0) 줄.push({ 이름: '마이너스통장 이자(한도 기준)', 연: (마통 * (Number(s.마통금리) || 0)) / 100 });
  const 기타 = Number(s.기타주담월) || 0;
  if (기타 > 0) 줄.push({ 이름: '다른 집 주담대 원리금', 연: (기타 * 12) / 10000 });
  const 학자금 = Number(s.학자금월) || 0;
  if (학자금 > 0 && s.학자금포함) 줄.push({ 이름: '학자금대출', 연: (학자금 * 12) / 10000 });
  const 통장 = 청약쓰기(s);
  if (통장.고름 === '담보' && 통장.연이자 > 0) 줄.push({ 이름: '청약통장 담보대출 이자', 연: 통장.연이자 });
  const 연 = 줄.reduce((a, b) => a + b.연, 0);
  return { 연, 월원: (연 * 10000) / 12, 줄 };
}

/** 만기선택 가운데 원하는 기간을 담을 수 있는 가장 짧은 것 */
function 만기맞추기(기간, 선택들) {
  const 찾음 = 선택들.find((y) => y >= 기간);
  return 찾음 ?? 선택들[선택들.length - 1];
}

function 부부합산(s) { return (Number(s.내소득) || 0) + (Number(s.배우자소득) || 0); }

/* ══════════════ 디딤돌 ══════════════ */

export function 디딤돌(s) {
  const R = 정책대출.디딤돌;
  const 신혼 = s.혼인 === '신혼';
  const 두자녀 = (Number(s.자녀수) || 0) >= 2;
  const 생최 = !!s.생애최초;
  const 소득 = 부부합산(s);
  const 담보 = 담보가치(s);
  const 가격 = Number(s.매매가) || 0;

  // 해당되는 갈래 가운데 가장 유리한 쪽
  const 갈래 = [{ 이름: '일반', 키: '일반' }];
  if (생최) 갈래.push({ 이름: '생애최초', 키: '생애최초' });
  if (두자녀) 갈래.push({ 이름: '2자녀 이상', 키: '두자녀' });
  if (신혼) 갈래.push({ 이름: '신혼', 키: '신혼' });
  const 소득상한 = Math.max(...갈래.map((g) => R.소득상한[g.키]));
  const 호당한도 = Math.max(...갈래.map((g) => R.한도[g.키]));
  const 가격상한 = Math.max(...갈래.map((g) => R.주택가격상한[g.키]));
  const 갈래이름 = 갈래.map((g) => g.이름).join('·');

  /* 신혼 「1인 소득」 예외는 8·13 대책에 들어 있지만 디딤돌은 아직 시행일이 확인되지 않았다.
     그래서 **계산에는 넣지 않고**, 「시행되면 될 수도 있다」고 알려만 준다. */
  const 내소득 = Number(s.내소득) || 0;
  const 배소득 = Number(s.배우자소득) || 0;
  const 적은쪽 = 배소득 > 0 ? Math.min(내소득, 배소득) : 내소득;
  const 시행되면 = 신혼 && 배소득 > 0 && 소득 > 소득상한 && 적은쪽 <= R.신혼1인.소득상한;

  const 자격 = [
    { 글: '세대원 전원 무주택', 통과: (Number(s.주택수) || 0) === 0 },
    { 글: `부부합산 소득 ${돈(소득상한)} 이하`, 통과: 소득 <= 소득상한, 값: `${소득.toLocaleString()}만원` },
    { 글: `집값 ${돈(가격상한)} 이하`, 통과: 담보 <= 가격상한, 값: `${담보.toLocaleString()}만원` },
    { 글: `전용면적 ${R.면적상한}㎡ 이하`, 통과: (Number(s.전용면적) || 0) <= R.면적상한, 값: `${s.전용면적}㎡` },
    { 글: `부부 순자산 ${(R.순자산상한 / 10000).toFixed(2)}억 이하`, 통과: null, 쪽지: '이 앱은 순자산을 모른다 — 스스로 확인할 것' },
    { 글: '다른 주택담보대출이 없다', 통과: (Number(s.기타주담월) || 0) === 0, 쪽지: '쓰고 있으면 받을 수 없다' },
  ];
  const 가능 = 자격.every((c) => c.통과 !== false);

  // LTV — 생애최초 80%, 수도권·규제지역이면 70%
  const ltv율 = 생최 ? (s.지역 === '지방' ? R.ltv.생애최초 : R.ltv.생애최초수도권) : R.ltv.기본;
  const 만기 = 만기맞추기(Number(s.기간) || 30, R.만기선택);
  const 금리줄 = R.금리표.find((r) => 소득 <= r.소득이하) || R.금리표[R.금리표.length - 1];
  let 금리 = 금리줄.금리[만기];
  if (s.지역 === '지방') 금리 -= R.지방우대;

  const 방공제액 = 방공제금액(s);
  const ltv값 = Math.max(0, 담보 * ltv율 - 방공제액);
  const 빚 = 기존부채DTI(s);
  const 월예산원 = (소득 * 10000 * R.dti) / 12 - 빚.월원;
  const dti값 = 월예산원 > 0 ? PV(금리 / 100 / 12, 만기 * 12, 월예산원) / 10000 : 0;

  const 항목 = [
    { 이름: '상품 한도', 값: 호당한도, 설명: `${갈래이름} 기준` },
    { 이름: 'LTV 한도', 값: ltv값, 설명: `${Math.round(ltv율 * 100)}% × 담보 ${담보.toLocaleString()}만원${방공제액 ? ` − 방공제 ${방공제액.toLocaleString()}만원` : ''}` },
    { 이름: 'DTI 한도', 값: dti값, 설명: `부부합산 소득의 ${Math.round(R.dti * 100)}% · 금리 ${금리.toFixed(2)}% · ${만기}년` },
    { 이름: '매매가', 값: 가격, 설명: '대출이 집값을 넘을 수는 없다' },
  ];
  const 한도 = 가능 ? Math.max(0, Math.min(...항목.map((a) => a.값))) : 0;

  return {
    키: '디딤돌', 이름: R.이름, 가능, 자격, 항목,
    한도, 묶은것: 항목.filter((a) => Math.abs(a.값 - 한도) < 1).map((a) => a.이름),
    금리, 금리설명: `소득 ${소득.toLocaleString()}만원 · ${만기}년 기준 공시금리${s.지역 === '지방' ? ` (지방 −${R.지방우대}%p 반영)` : ''}. 청약저축·전자계약 우대로 최대 ${R.우대최대}%p 더 내려갈 수 있다.`,
    만기, ltv율, dti율: R.dti, 갈래이름, 메모: R.메모,
    시행되면, 신혼1인: R.신혼1인, 적은쪽, 합산: 소득,
  };
}

/* ══════════════ 보금자리론 ══════════════ */

export function 보금자리론(s) {
  const R = 정책대출.보금자리론;
  const 신혼 = s.혼인 === '신혼';
  const 자녀 = Number(s.자녀수) || 0;
  const 생최 = !!s.생애최초;
  const 소득 = 부부합산(s);
  const 담보 = 담보가치(s);
  const 가격 = Number(s.매매가) || 0;
  const kb = Number(s.kb시세) || 0;
  const 주택수 = Number(s.주택수) || 0;

  const 갈래 = [{ 이름: '일반', 상한: R.소득상한.일반 }];
  if (신혼) 갈래.push({ 이름: '신혼', 상한: R.소득상한.신혼 });
  if (자녀 === 1) 갈래.push({ 이름: '1자녀', 상한: R.소득상한.한자녀 });
  if (자녀 >= 2) 갈래.push({ 이름: '다자녀', 상한: R.소득상한.다자녀 });
  const 소득상한 = Math.max(...갈래.map((g) => g.상한));
  const 갈래이름 = 갈래.map((g) => g.이름).join('·');

  /* ★ 신혼가구 「1인 소득」 예외 (2026-10-19 신규 신청분부터)
     부부합산이 상한을 넘어도, 적게 버는 쪽이 7천만원 이하면 **그 사람이 차주**가 되어 받을 수 있다.
     그때는 DTI 도 그 한 사람의 소득으로 본다 — 한도가 오히려 줄 수 있으니 자동으로 유리한 쪽을 고르지 않고
     「합산으로는 안 되는 경우」에만 쓴다. */
  const 내소득 = Number(s.내소득) || 0;
  const 배소득 = Number(s.배우자소득) || 0;
  const 적은쪽 = 배소득 > 0 ? Math.min(내소득, 배소득) : 내소득;
  const 합산으로가능 = 소득 <= 소득상한;
  const 한사람기준 = 신혼 && !합산으로가능 && 배소득 > 0 && 적은쪽 <= R.신혼1인.소득상한;
  /** 소득 심사에 실제로 쓰는 금액 */
  const 심사소득 = 한사람기준 ? 적은쪽 : 소득;

  // 집값 6억은 매매가·시세 어느 하나라도 넘으면 안 된다
  const 가격넘음 = 가격 > R.주택가격상한 || (kb > 0 && kb > R.주택가격상한);
  const 자격 = [
    {
      글: 주택수 === 0 ? '무주택' : '기존 집을 3년 안에 파는 조건',
      통과: 주택수 === 0 || (주택수 === 1 && !!s.처분조건),
      쪽지: 주택수 >= 2 ? '2주택 이상은 안 된다' : null,
    },
    {
      글: 한사람기준
        ? `적게 버는 쪽 소득 ${돈(R.신혼1인.소득상한)} 이하 — ${R.신혼1인.날짜}부터 생긴 신혼 1인 기준`
        : `부부합산 소득 ${돈(소득상한)} 이하`,
      통과: 합산으로가능 || 한사람기준,
      값: 한사람기준
        ? `합산 ${소득.toLocaleString()} → 1인 ${적은쪽.toLocaleString()}만원으로 신청`
        : `${소득.toLocaleString()}만원`,
      쪽지: 한사람기준 ? R.신혼1인.주의 : null,
    },
    {
      글: '집값 6억 이하 (매매가·시세·감정가 모두)',
      통과: !가격넘음,
      값: kb > 0 ? `매매가 ${가격.toLocaleString()} · 시세 ${kb.toLocaleString()}만원` : `${가격.toLocaleString()}만원`,
    },
  ];
  const 가능 = 자격.every((c) => c.통과 !== false);

  // 실수요자(또는 생애최초)면 규제지역 차감을 받지 않는다
  const 실수요 = 주택수 === 0 && !가격넘음 && 소득 <= R.소득상한.일반;
  const 차감면제 = 실수요 || 생최;
  const 규제차감 = s.지역 === '규제' && !차감면제;

  let ltv율;
  if (생최) ltv율 = s.지역 === '지방' ? R.ltv.생애최초 : R.ltv.생애최초수도권;
  else ltv율 = (s.아파트 ? R.ltv.아파트 : R.ltv.비아파트) - (규제차감 ? R.ltv.규제차감 : 0);
  const dti율 = 규제차감 ? R.dti.규제 : R.dti.기본;

  const 호당한도 = 생최 ? R.한도.생애최초 : (자녀 >= 2 ? R.한도.다자녀 : R.한도.일반);
  const 만기 = 만기맞추기(Number(s.기간) || 30, R.만기선택);
  const 금리 = R.금리.최고 + (s.지역 === '규제' ? R.금리.규제가산 : 0);

  const 방공제액 = 방공제금액(s);
  const ltv값 = Math.max(0, 담보 * ltv율 - 방공제액);
  const 빚 = 기존부채DTI(s);
  const 월예산원 = (심사소득 * 10000 * dti율) / 12 - 빚.월원;
  const dti값 = 월예산원 > 0 ? PV(금리 / 100 / 12, 만기 * 12, 월예산원) / 10000 : 0;

  const 항목 = [
    { 이름: '상품 한도', 값: 호당한도, 설명: 생최 ? '생애최초 4.2억' : (자녀 >= 2 ? '다자녀 4억' : '일반 3.6억') },
    { 이름: 'LTV 한도', 값: ltv값, 설명: `${Math.round(ltv율 * 100)}% × 담보 ${담보.toLocaleString()}만원${규제차감 ? ' (규제지역 −10%p)' : ''}${방공제액 ? ` − 방공제 ${방공제액.toLocaleString()}만원` : ''}` },
    {
      이름: 'DTI 한도',
      값: dti값,
      설명: `${한사람기준 ? `차주 한 사람 소득 ${적은쪽.toLocaleString()}만원` : '부부합산 소득'}의 ${Math.round(dti율 * 100)}% · 금리 ${금리.toFixed(2)}% · ${만기}년`,
    },
    { 이름: '매매가', 값: 가격, 설명: '대출이 집값을 넘을 수는 없다' },
  ];
  const 한도 = 가능 ? Math.max(0, Math.min(...항목.map((a) => a.값))) : 0;

  return {
    키: '보금자리론', 이름: R.이름, 가능, 자격, 항목,
    한도, 묶은것: 항목.filter((a) => Math.abs(a.값 - 한도) < 1).map((a) => a.이름),
    금리,
    금리설명: `${R.금리.공시월} 공시 ${R.금리.최저}~${R.금리.최고}%${s.지역 === '규제' ? ` + 규제지역 ${R.금리.규제가산}%p` : ''}. 셈에는 높은 쪽을 썼다 — 우대(최대 ${R.금리.우대최대}%p)를 받으면 더 내려간다.`,
    만기, ltv율, dti율, 갈래이름, 차감면제, 실수요, 메모: R.메모, 신혼1인: R.신혼1인, 한사람기준, 심사소득,
  };
}

/** 정책대출 두 상품을 한꺼번에 */
export function 정책후보(s) {
  return [디딤돌(s), 보금자리론(s)];
}
