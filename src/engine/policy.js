/**
 * 이미 다른 칸에서 물어본 조건은 저절로 켜진다. 두 번 묻지 않는다.
 * (두 번 물으면 「② 에서는 신혼인데 여기서는 안 눌렀다」 같은 어긋남이 생긴다.)
 * 돌려주는 값이 null 이면 자동으로 알 수 없다는 뜻 — 그때는 사용자가 고른 값을 쓴다.
 *
 * ⚠ 청약저축 구간은 **가입 햇수만으로 어림한다.** 진짜 요건은 「가입 15년 + 납입 180회」처럼
 *   회차까지 보는데 이 앱은 회차를 모른다(빠짐없이 냈다고 본 셈이다). 화면에 그렇게 밝힌다.
 */
function 자동켜짐(s, 키) {
  const 자녀 = Number(s.자녀수) || 0;
  const 주택수 = Number(s.주택수) || 0;
  const 청약년 = Number(s.청약가입년) || 0;
  const 청약살아있나 = (Number(s.청약잔액) || 0) > 0 && (s.청약선택 || '유지') !== '해지';
  if (키 === '신혼') return s.혼인 === '신혼';
  if (키 === '한자녀') return 자녀 === 1;
  if (키 === '두자녀') return 자녀 === 2;
  if (키 === '세자녀') return 자녀 >= 3;
  if (키 === '생애최초') return !!s.생애최초 && 주택수 === 0;
  if (키 === '청약15') return 청약살아있나 && 청약년 >= 15;
  if (키 === '청약10') return 청약살아있나 && 청약년 >= 10;
  if (키 === '청약5') return 청약살아있나 && 청약년 >= 5;
  return null;
}

/**
 * 함께 받을 수 없는 것들을 정리한다.
 * ① 같은 `묶음` 에서는 **깎아 주는 폭이 큰 것부터 정해진 개수만** 남긴다
 *    (디딤돌 가구 우대는 하나, 보금자리론 사회적 배려층은 둘까지).
 * ② `배타` 로 맺어진 쌍은 큰 쪽만 남긴다 (보금자리론 신혼 ↔ 신생아).
 */
function 하나만남기기(켜진것, 묶음상한) {
  const 묶음별 = new Map();
  const 남김 = [];
  for (const r of 켜진것) {
    if (!r.묶음) { 남김.push(r); continue; }
    if (!묶음별.has(r.묶음)) 묶음별.set(r.묶음, []);
    묶음별.get(r.묶음).push(r);
  }
  for (const [이름, 것들] of 묶음별) {
    const 몇개 = (묶음상한 || {})[이름] || 1;
    것들.sort((a, b) => b.값 - a.값);
    남김.push(...것들.slice(0, 몇개));
  }

  const 뺄것 = new Set();
  for (const a of 남김) {
    if (!a.배타) continue;
    for (const b of 남김) {
      if (a === b || !a.배타.includes(b.키)) continue;
      뺄것.add(a.값 > b.값 ? b.키 : a.키);
    }
  }
  return 남김.filter((r) => !뺄것.has(r.키));
}

/** 합계 상한 — 디딤돌은 자녀가 있으면 더 높다 */
function 상한구하기(s, W) {
  if (W.다자녀상한 && (Number(s.자녀수) || 0) >= (W.다자녀기준자녀수 || 2)) return W.다자녀상한;
  return W.상한;
}

/**
 * 우대금리를 셈한다. 두 상품이 같은 틀로 돌되 규칙은 표에서 읽는다.
 * ⚠ 숫자는 하나도 여기 없다 — 전부 `rules.js` 의 표에서 온다.
 * ⚠⚠ **대출 자격 소득과 우대 소득이 다르다.** 신혼은 8,500만원까지 빌릴 수 있어도
 *   우대 0.3%p 는 부부합산 7,000만원 이하만 받는다. 그래서 항목마다 소득을 다시 본다.
 *
 * @param 뺄것 표 B(생애최초 신혼) 처럼 **금리표에서 이미 깎아 준** 우대의 키 목록
 */
export function 우대셈(s, W, 뺄것) {
  const 빈값 = { 전부: [], 켜진것: [], 합: 0, 깎은값: 0, 잘림: 0, 아낌e: 0, 총깎음: 0, 상한: 0 };
  if (!W || !W.항목) return 빈값;

  const 합산소득 = 부부합산(s);
  const 내소득 = Number(s.내소득) || 0;
  const 빼기 = new Set(뺄것 || []);

  const 전부 = W.항목.map((항) => {
    const 자동 = 자동켜짐(s, 항.키);
    const 골랐나 = 자동 !== null ? 자동 : !!s[`우대${항.키}`];
    /* 소득이 넘으면 골랐어도 못 받는다 — 왜 안 켜졌는지 화면이 말해 줄 수 있게 까닭을 남긴다 */
    let 막힌까닭 = null;
    if (골랐나 && 항.소득이하 && 합산소득 > 항.소득이하) {
      막힌까닭 = `부부합산 소득 ${합산소득.toLocaleString()}만원이 우대 기준 ${항.소득이하.toLocaleString()}만원을 넘습니다`;
    }
    if (골랐나 && 항.본인소득이하 && 내소득 > 항.본인소득이하) {
      막힌까닭 = `본인 소득 ${내소득.toLocaleString()}만원이 우대 기준 ${항.본인소득이하.toLocaleString()}만원을 넘습니다`;
    }
    if (골랐나 && 빼기.has(항.키)) 막힌까닭 = '전용 금리표에서 이미 깎아 주었습니다 (두 번 빼지 않습니다)';
    return { ...항, 자동켜짐: 자동 !== null, 골랐나, 막힌까닭, 켜짐: 골랐나 && !막힌까닭 };
  });

  const 상한 = 상한구하기(s, W);
  const 켜진것 = 하나만남기기(전부.filter((r) => r.켜짐), W.묶음상한);
  const 합 = 켜진것.reduce((a, b) => a + b.값, 0);
  const 깎은값 = Math.min(합, 상한);
  const 아낌e = (W.아낌e && s[`우대${W.아낌e.키}`]) ? W.아낌e.값 : 0;
  return {
    전부, 켜진것, 합, 깎은값,
    잘림: 합 - 깎은값,
    아낌e, 총깎음: 깎은값 + 아낌e, 상한,
    /** 규제지역 가산을 면제받는가 (전세사기피해자) */
    규제가산면제: 켜진것.some((r) => r.규제가산면제),
  };
}

/* ══════════════ 디딤돌 ══════════════ */

export function 디딤돌(s) {
  const R = 정책대출.디딤돌;
  const 신혼 = s.혼인 === '신혼';
  const 두자녀 = (Number(s.자녀수) || 0) >= 2;
  const 생최 = !!s.생애최초;
  const 소득 = 부부합산(s);
  const 담보 = 담보가치(s);
  const 가격 = Number(s.매매가) || 0;

  // 해당되는 갈래 가운데 가장 유리한 쪽
  const 갈래 = [{ 이름: '일반', 키: '일반' }];
  if (생최) 갈래.push({ 이름: '생애최초', 키: '생애최초' });
  if (두자녀) 갈래.push({ 이름: '2자녀 이상', 키: '두자녀' });
  if (신혼) 갈래.push({ 이름: '신혼', 키: '신혼' });
  const 소득상한 = Math.max(...갈래.map((g) => R.소득상한[g.키]));
  const 호당한도 = Math.max(...갈래.map((g) => R.한도[g.키]));
  const 가격상한 = Math.max(...갈래.map((g) => R.주택가격상한[g.키]));
  const 갈래이름 = 갈래.map((g) => g.이름).join('·');

  /* 신혼 「1인 소득」 예외는 8·13 대책에 들어 있지만 디딤돌은 아직 시행일이 확인되지 않았다.
     그래서 **계산에는 넣지 않고**, 「시행되면 될 수도 있다」고 알려만 준다. */
  const 내소득 = Number(s.내소득) || 0;
  const 배소득 = Number(s.배우자소득) || 0;
  const 적은쪽 = 배소득 > 0 ? Math.min(내소득, 배소득) : 내소득;
  const 시행되면 = 신혼 && 배소득 > 0 && 소득 > 소득상한 && 적은쪽 <= R.신혼1인.소득상한;

  const 자격 = [
    { 글: '세대원 전원 무주택', 통과: (Number(s.주택수) || 0) === 0 },
    { 글: `부부합산 소득 ${돈(소득상한)} 이하`, 통과: 소득 <= 소득상한, 값: `${소득.toLocaleString()}만원` },
    { 글: `집값 ${돈(가격상한)} 이하`, 통과: 담보 <= 가격상한, 값: `${담보.toLocaleString()}만원` },
    { 글: `전용면적 ${R.면적상한}㎡ 이하`, 통과: (Number(s.전용면적) || 0) <= R.면적상한, 값: `${s.전용면적}㎡` },
    { 글: `부부 순자산 ${(R.순자산상한 / 10000).toFixed(2)}억 이하`, 통과: null, 쪽지: '이 앱은 순자산을 모른다 — 스스로 확인할 것' },
    { 글: '다른 주택담보대출이 없다', 통과: (Number(s.기타주담월) || 0) === 0, 쪽지: '쓰고 있으면 받을 수 없다' },
  ];
  const 가능 = 자격.every((c) => c.통과 !== false);

  // LTV — 생애최초 80%, 수도권·규제지역이면 70%
  const ltv율 = 생최 ? (s.지역 === '지방' ? R.ltv.생애최초 : R.ltv.생애최초수도권) : R.ltv.기본;
  const 만기 = 만기맞추기(Number(s.기간) || 30, R.만기선택);
  const 금리줄 = R.금리표.find((r) => 소득 <= r.소득이하) || R.금리표[R.금리표.length - 1];
  let 공시금리 = 금리줄.금리[만기];
  if (s.지역 === '지방') 공시금리 = 소수둘(공시금리 - R.지방우대);

  /* ★ 생애최초인 신혼가구는 **전용 금리표(표 B)** 를 쓴다 — 표 A 보다 0.3%p 낮다.
     그때는 신혼·생애최초 우대를 또 빼지 않는다(이중으로 깎이면 안 된다). */
  const 표B = R.우대금리.생애최초신혼표;
  const 표B쓰나 = !!(표B && 신혼 && 생최);
  if (표B쓰나) 공시금리 = 소수둘(공시금리 - 표B.차감);

  /* ★ 우대금리 — 깎아 주는 만큼 월 상환액이 줄고, 그만큼 **DTI 한도가 늘어난다.**
     다만 우대를 다 받아도 하한 아래로는 내려가지 않는다. */
  const 우대 = 우대셈(s, R.우대금리, 표B쓰나 ? 표B.빼는우대 : null);
  // 하한은 표마다 다르다 — 표 A 1.5% · 표 B 1.2%
  const 하한 = 표B쓰나 ? R.우대금리.표B하한금리 : R.우대금리.하한금리;
  const 금리 = 소수둘(Math.max(하한, 공시금리 - 우대.총깎음));
  const 실제깎음 = 소수둘(공시금리 - 금리);
  const 심사금리 = R.우대금리.dti반영 ? 금리 : 공시금리;

  const 방공제액 = 방공제금액(s);
  const ltv값 = Math.max(0, 담보 * ltv율 - 방공제액);
  const 빚 = 기존부채DTI(s);
  const 월예산원 = (소득 * 10000 * R.dti) / 12 - 빚.월원;
  const dti값 = 월예산원 > 0 ? PV(심사금리 / 100 / 12, 만기 * 12, 월예산원) / 10000 : 0;

  const 항목 = [
    { 이름: '상품 한도', 값: 호당한도, 설명: `${갈래이름} 기준` },
    { 이름: 'LTV 한도', 값: ltv값, 설명: `${Math.round(ltv율 * 100)}% × 담보 ${담보.toLocaleString()}만원${방공제액 ? ` − 방공제 ${방공제액.toLocaleString()}만원` : ''}` },
    { 이름: 'DTI 한도', 값: dti값, 설명: `부부합산 소득의 ${Math.round(R.dti * 100)}% · 금리 ${심사금리.toFixed(2)}% · ${만기}년` },
    { 이름: '매매가', 값: 가격, 설명: '대출이 집값을 넘을 수는 없다' },
  ];
  const 한도 = 가능 ? Math.max(0, Math.min(...항목.map((a) => a.값))) : 0;

  return {
    키: '디딤돌', 이름: R.이름, 가능, 자격, 항목,
    한도, 묶은것: 항목.filter((a) => Math.abs(a.값 - 한도) < 1).map((a) => a.이름),
    금리,
    금리설명: `공시 ${공시금리.toFixed(2)}%(소득 ${소득.toLocaleString()}만원 · ${만기}년${s.지역 === '지방' ? ` · 지방 −${R.지방우대}%p` : ''}${표B쓰나 ? ' · 생애최초 신혼 전용표 −0.30%p' : ''})`
      + (실제깎음 > 0 ? ` − 우대 ${실제깎음.toFixed(2)}%p = ${금리.toFixed(2)}%` : ' — 지금 고른 조건으로는 우대가 없다'),
    공시금리, 우대, 실제깎음, 심사금리, 하한금리: 하한, 표B쓰나,
    만기, ltv율, dti율: R.dti, 갈래이름, 메모: R.메모,
    시행되면, 신혼1인: R.신혼1인, 적은쪽, 합산: 소득,
  };
}

/* ══════════════ 보금자리론 ══════════════ */

export function 보금자리론(s) {
  const R = 정책대출.보금자리론;
  const 신혼 = s.혼인 === '신혼';
  const 자녀 = Number(s.자녀수) || 0;
  const 소득 = 부부합산(s);
  const 담보 = 담보가치(s);
  const 가격 = Number(s.매매가) || 0;
  const kb = Number(s.kb시세) || 0;
  const 주택수 = Number(s.주택수) || 0;
  /* ⚠ 집을 가지고 있으면 생애최초일 수 없다 (2026-10-10 검토에서 잡은 결함).
     예전에는 스위치만 보아, 1주택자에게도 LTV 70%·상품한도 4.2억·규제차감 면제를 주어
     한도가 5,000만원 넘게 부풀려 나왔다. 은행 한도·취득세 쪽은 원래 주택수를 보고 있었다. */
  const 생최 = !!s.생애최초 && 주택수 === 0;

  const 갈래 = [{ 이름: '일반', 상한: R.소득상한.일반 }];
  if (신혼) 갈래.push({ 이름: '신혼', 상한: R.소득상한.신혼 });
  if (자녀 === 1) 갈래.push({ 이름: '1자녀', 상한: R.소득상한.한자녀 });
  if (자녀 >= 2) 갈래.push({ 이름: '다자녀', 상한: R.소득상한.다자녀 });
  const 소득상한 = Math.max(...갈래.map((g) => g.상한));
  const 갈래이름 = 갈래.map((g) => g.이름).join('·');

  /* ★ 신혼가구 「1인 소득」 예외 (2026-10-19 신규 신청분부터)
     부부합산이 상한을 넘어도, 적게 버는 쪽이 7천만원 이하면 **그 사람이 차주**가 되어 받을 수 있다.
     그때는 DTI 도 그 한 사람의 소득으로 본다 — 한도가 오히려 줄 수 있으니 자동으로 유리한 쪽을 고르지 않고
     「합산으로는 안 되는 경우」에만 쓴다. */
  const 내소득 = Number(s.내소득) || 0;
  const 배소득 = Number(s.배우자소득) || 0;
  const 적은쪽 = 배소득 > 0 ? Math.min(내소득, 배소득) : 내소득;
  const 합산으로가능 = 소득 <= 소득상한;
  const 한사람기준 = 신혼 && !합산으로가능 && 배소득 > 0 && 적은쪽 <= R.신혼1인.소득상한;
  /** 소득 심사에 실제로 쓰는 금액 */
  const 심사소득 = 한사람기준 ? 적은쪽 : 소득;

  // 집값 6억은 매매가·시세 어느 하나라도 넘으면 안 된다
  const 가격넘음 = 가격 > R.주택가격상한 || (kb > 0 && kb > R.주택가격상한);
  const 자격 = [
    {
      글: 주택수 === 0 ? '무주택' : '기존 집을 3년 안에 파는 조건',
      통과: 주택수 === 0 || (주택수 === 1 && !!s.처분조건),
      쪽지: 주택수 >= 2 ? '2주택 이상은 안 된다' : null,
    },
    {
      글: 한사람기준
        ? `적게 버는 쪽 소득 ${돈(R.신혼1인.소득상한)} 이하 — ${R.신혼1인.날짜}부터 생긴 신혼 1인 기준`
        : `부부합산 소득 ${돈(소득상한)} 이하`,
      통과: 합산으로가능 || 한사람기준,
      값: 한사람기준
        ? `합산 ${소득.toLocaleString()} → 1인 ${적은쪽.toLocaleString()}만원으로 신청`
        : `${소득.toLocaleString()}만원`,
      쪽지: 한사람기준 ? R.신혼1인.주의 : null,
    },
    {
      글: '집값 6억 이하 (매매가·시세·감정가 모두)',
      통과: !가격넘음,
      값: kb > 0 ? `매매가 ${가격.toLocaleString()} · 시세 ${kb.toLocaleString()}만원` : `${가격.toLocaleString()}만원`,
    },
  ];
  const 가능 = 자격.every((c) => c.통과 !== false);

  // 실수요자(또는 생애최초)면 규제지역 차감을 받지 않는다
  const 실수요 = 주택수 === 0 && !가격넘음 && 소득 <= R.소득상한.일반;
  const 차감면제 = 실수요 || 생최;
  const 규제차감 = s.지역 === '규제' && !차감면제;

  let ltv율;
  if (생최) ltv율 = s.지역 === '지방' ? R.ltv.생애최초 : R.ltv.생애최초수도권;
  else ltv율 = (s.아파트 ? R.ltv.아파트 : R.ltv.비아파트) - (규제차감 ? R.ltv.규제차감 : 0);
  const dti율 = 규제차감 ? R.dti.규제 : R.dti.기본;

  const 호당한도 = 생최 ? R.한도.생애최초 : (자녀 >= 2 ? R.한도.다자녀 : R.한도.일반);
  const 만기 = 만기맞추기(Number(s.기간) || 30, R.만기선택);
  /* ★ 우대금리 — 이것은 꾸밈이 아니라 **한도를 바꾼다.**
     DTI 한도는 「월 상환 여력으로 갚을 수 있는 원금」을 금리로 역산한 값이라,
     금리가 내려가면 같은 소득으로 더 많이 빌릴 수 있다. */
  const 우대 = 우대셈(s, R.우대금리);

  /* 공시금리는 **만기마다 다르다.** 표에 없는 만기면 가장 비싼 값으로 보수적으로 본다.
     규제지역 가산 0.2%p 는 우대 상한과 따로 붙고, 면제되는 것은 전세사기피해자뿐이다. */
  const 규제가산 = (s.지역 === '규제' && !우대.규제가산면제) ? R.금리.규제가산 : 0;
  const 공시금리 = 소수둘((R.금리.만기별[만기] ?? R.금리.최고) + 규제가산);
  const 금리 = 소수둘(Math.max(0, 공시금리 - 우대.총깎음));
  const 실제깎음 = 소수둘(공시금리 - 금리);
  const 심사금리 = R.우대금리.dti반영 ? 금리 : 공시금리;

  const 방공제액 = 방공제금액(s);
  const ltv값 = Math.max(0, 담보 * ltv율 - 방공제액);
  const 빚 = 기존부채DTI(s);
  const 월예산원 = (심사소득 * 10000 * dti율) / 12 - 빚.월원;
  const dti값 = 월예산원 > 0 ? PV(심사금리 / 100 / 12, 만기 * 12, 월예산원) / 10000 : 0;

  const 항목 = [
    { 이름: '상품 한도', 값: 호당한도, 설명: 생최 ? '생애최초 4.2억' : (자녀 >= 2 ? '다자녀 4억' : '일반 3.6억') },
    { 이름: 'LTV 한도', 값: ltv값, 설명: `${Math.round(ltv율 * 100)}% × 담보 ${담보.toLocaleString()}만원${규제차감 ? ' (규제지역 −10%p)' : ''}${방공제액 ? ` − 방공제 ${방공제액.toLocaleString()}만원` : ''}` },
    {
      이름: 'DTI 한도',
      값: dti값,
      설명: `${한사람기준 ? `차주 한 사람 소득 ${적은쪽.toLocaleString()}만원` : '부부합산 소득'}의 ${Math.round(dti율 * 100)}% · 금리 ${심사금리.toFixed(2)}% · ${만기}년`,
    },
    { 이름: '매매가', 값: 가격, 설명: '대출이 집값을 넘을 수는 없다' },
  ];
  const 한도 = 가능 ? Math.max(0, Math.min(...항목.map((a) => a.값))) : 0;

  return {
    키: '보금자리론', 이름: R.이름, 가능, 자격, 항목, 생최,
    한도, 묶은것: 항목.filter((a) => Math.abs(a.값 - 한도) < 1).map((a) => a.이름),
    금리,
    금리설명: `${R.금리.공시월} 공시 ${만기}년 ${R.금리.만기별[만기] ?? R.금리.최고}%${규제가산 ? ` + 규제지역 ${규제가산}%p` : ''} = ${공시금리.toFixed(2)}%`
      + (실제깎음 > 0 ? ` − 우대 ${실제깎음.toFixed(2)}%p = ${금리.toFixed(2)}%` : ' — 지금 고른 조건으로는 우대가 없다'),
    공시금리, 우대, 실제깎음, 심사금리,
    만기, ltv율, dti율, 갈래이름, 차감면제, 실수요, 메모: R.메모, 신혼1인: R.신혼1인, 한사람기준, 심사소득,
  };
}

/** 정책대출 두 상품을 한꺼번에 */
export function 정책후보(s) {
  return [디딤돌(s), 보금자리론(s)];
}
