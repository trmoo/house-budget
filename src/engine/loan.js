import { 지역표, dsr as DSR, 서민실수요요건, 부대비용 } from '../rules.js';
import { 청약쓰기 } from './cash.js';

/**
 * 방공제 — 보증보험(MCI·MCG)을 못 붙이면 LTV 한도에서 소액임차보증금을 뺀다.
 * ⚠ 2026년 7월에 5대 은행이 모두 가입을 중단했다가 일부만 다시 열었다. 그래서 기본은 「빠진다」로 둔다.
 */
export function 방공제금액(s) {
  if (!s.방공제) return 0;
  const 줄 = 부대비용.방공제.find((r) => r.키 === s.방공제지역);
  return 줄 ? 줄.값 : 0;
}

/** 원리금균등 월 상환액 */
export function PMT(월이율, 개월, 원금) {
  if (!개월 || 개월 <= 0) return 0;
  if (월이율 === 0) return 원금 / 개월;
  return (원금 * 월이율) / (1 - Math.pow(1 + 월이율, -개월));
}

/** 월 상환액으로 빌릴 수 있는 원금 (PMT 의 반대) */
export function PV(월이율, 개월, 월상환) {
  if (!개월 || 개월 <= 0 || 월상환 <= 0) return 0;
  if (월이율 === 0) return 월상환 * 개월;
  return (월상환 * (1 - Math.pow(1 + 월이율, -개월))) / 월이율;
}

/**
 * 이미 있는 빚이 DSR 에서 얼마로 셈해지나. (만원/년)
 *
 * ★ 여기가 보통 계산기와 가장 많이 다르다. 「실제로 내는 월 상환액」이 아니라
 *   규정이 정한 방식으로 셈한다 — 마이너스통장은 **쓴 돈이 아니라 한도 전액**을 5년에 나누고,
 *   신용대출도 실제 만기와 무관하게 5년에 나눈다. 자동차 할부·리스는 아예 빠진다.
 *   (스트레스 금리는 새로 받는 대출에만 붙으므로 기존 빚에는 더하지 않는다.)
 */
export function 기존부채(s) {
  const 줄 = [];
  const 더하기 = (이름, 연, 설명) => { if (연 > 0) 줄.push({ 이름, 연, 설명 }); };

  const 신용 = Number(s.신용잔액) || 0;
  if (신용 > 0) {
    const 원금 = 신용 / DSR.신용대출산정만기;
    const 이자 = (신용 * (Number(s.신용금리) || 0)) / 100;
    더하기('신용대출', 원금 + 이자,
      `잔액 ${신용.toLocaleString()}만원 ÷ ${DSR.신용대출산정만기}년 + 이자 — 실제 만기가 더 길어도 규정이 ${DSR.신용대출산정만기}년으로 셈한다`);
  }

  const 마통 = Number(s.마통한도) || 0;
  if (마통 > 0) {
    const 원금 = 마통 / DSR.마통산정만기;
    const 이자 = (마통 * (Number(s.마통금리) || 0)) / 100;
    더하기('마이너스통장', 원금 + 이자,
      `한 푼도 안 썼어도 **한도 ${마통.toLocaleString()}만원 전액**을 ${DSR.마통산정만기}년에 나눠 셈한다`);
  }

  const 기타주담월원 = Number(s.기타주담월) || 0;
  if (기타주담월원 > 0) 더하기('다른 집의 주담대', (기타주담월원 * 12) / 10000, '실제 월 상환액 그대로');

  const 학자금월원 = Number(s.학자금월) || 0;
  if (학자금월원 > 0 && s.학자금포함) {
    더하기('학자금대출', (학자금월원 * 12) / 10000, '금융회사에 따라 빠질 수도 있다 — 스위치로 끌 수 있게 두었다');
  }

  // 청약통장 담보대출 — 예·적금담보대출이라 **원금은 빠지고 이자만** 들어간다
  const 통장 = 청약쓰기(s);
  if (통장.고름 === '담보' && 통장.연이자 > 0) {
    더하기('청약통장 담보대출 이자', 통장.연이자,
      `원금 ${Math.round(통장.대출).toLocaleString()}만원은 DSR 에서 빠지고 **이자만** 들어간다`);
  }

  const 연 = 줄.reduce((a, b) => a + b.연, 0);
  const 제외줄 = [];
  if (통장.고름 === '담보' && 통장.대출 > 0) {
    제외줄.push({ 이름: '청약통장 담보대출 원금', 월원: 0, 설명: `${Math.round(통장.대출).toLocaleString()}만원 — 예·적금담보대출이라 원금은 DSR 에 넣지 않는다` });
  }
  if ((Number(s.할부월) || 0) > 0) {
    제외줄.push({ 이름: '자동차 할부·리스', 월원: Number(s.할부월), 설명: 'DSR 산정에서 빠진다(신용점수에는 영향이 있다)' });
  }
  if (학자금월원 > 0 && !s.학자금포함) {
    제외줄.push({ 이름: '학자금대출', 월원: 학자금월원, 설명: '빼기로 해 두었다' });
  }
  return { 연, 월원: (연 * 10000) / 12, 줄, 제외줄 };
}

/** 담보로 인정되는 값 — 매매가와 KB시세 중 낮은 쪽 */
export function 담보가치(s) {
  const kb = Number(s.kb시세) || 0;
  const 가격 = Number(s.매매가) || 0;
  return kb > 0 ? Math.min(가격, kb) : 가격;
}

/** 서민·실수요자 우대에 해당하나 (규제지역에서만 뜻이 있다) */
export function 서민실수요(s) {
  const 합산 = (Number(s.내소득) || 0) + (Number(s.배우자소득) || 0);
  const 가격 = Number(s.매매가) || 0;
  const 조건 = [
    { 글: '무주택', 통과: (Number(s.주택수) || 0) === 0 },
    // ⚠ 그냥 무주택이 아니라 무주택 「세대주」여야 한다 (금융위 10.15 FAQ 주5).
    //   빼면 규제지역 LTV 를 20%p 부풀려 셈한다.
    { 글: '무주택 「세대주」', 통과: !서민실수요요건.세대주필요 || !!s.세대주, 쪽지: 서민실수요요건.세대주뜻 },
    { 글: `부부합산 소득 ${서민실수요요건.소득상한.toLocaleString()}만원 이하`, 통과: 합산 <= 서민실수요요건.소득상한, 값: `${합산.toLocaleString()}만원` },
    { 글: `집값 ${(서민실수요요건.가격상한 / 10000)}억원 이하`, 통과: 가격 <= 서민실수요요건.가격상한, 값: `${가격.toLocaleString()}만원` },
  ];
  return { 해당: 조건.every((c) => c.통과), 조건 };
}

/** 지역별 주담대 상한 (시가 구간별). 없으면 null */
export function 지역상한(지역키, 시가) {
  const 지 = 지역표[지역키];
  if (!지 || !지.상한) return null;
  const 찾음 = 지.상한.find(([기준]) => 시가 <= 기준);
  return 찾음 ? 찾음[1] : null;
}

/**
 * 시중은행 주담대 한도.
 * 돌려주는 것: { 가능, 금지이유, 한도, 항목[], 묶은것[], 경고[], 만기, 스트레스, 심사금리 }
 */
export function 은행한도(s) {
  const 지 = 지역표[s.지역] || 지역표.규제;
  const 담보 = 담보가치(s);
  const 주택수 = Number(s.주택수) || 0;
  const 경고 = [];

  // ① 아예 받을 수 없는 경우부터
  if (지.추가구입제한 && 주택수 >= 2) {
    return { 가능: false, 금지이유: `${지.이름}에서는 2주택 이상인 사람이 집을 더 살 때 주택담보대출을 받을 수 없습니다.`, 한도: 0, 항목: [], 묶은것: [], 경고, 지역: 지 };
  }
  if (지.추가구입제한 && 주택수 === 1 && !s.처분조건) {
    return {
      가능: false,
      금지이유: `${지.이름}에서 1주택자가 집을 더 사려면 **기존 집을 6개월 안에 파는 조건**이어야 주택담보대출이 나옵니다.`,
      한도: 0, 항목: [], 묶은것: [], 경고, 지역: 지,
    };
  }

  // ② LTV — 해당되는 우대 가운데 가장 높은 비율을 쓴다
  const 갈래 = [];
  if (주택수 === 0) {
    갈래.push({ 키: '무주택', 이름: '무주택자', 율: 지.ltv.무주택 });
    if (s.생애최초) 갈래.push({ 키: '생애최초', 이름: '생애최초', 율: 지.ltv.생애최초 });
    const 서민 = 서민실수요(s);
    if (서민.해당) 갈래.push({ 키: '서민실수요', 이름: '서민·실수요자', 율: 지.ltv.서민실수요 });
  } else {
    갈래.push({ 키: '처분조건1주택', 이름: '처분조건부 1주택자', 율: 지.ltv.처분조건1주택 });
  }
  const 고른것 = 갈래.reduce((a, b) => (b.율 > a.율 ? b : a));
  const 방공제액 = 방공제금액(s);
  const ltv값 = Math.max(0, 담보 * 고른것.율 - 방공제액);

  // ③ DSR — 스트레스 금리를 얹은 금리로 심사한다
  const 비율 = DSR.스트레스비율[s.금리유형] ?? 1;
  const 스트레스 = 지.스트레스 * 비율;
  const 만기 = 지.최장만기 ? Math.min(Number(s.기간) || 0, 지.최장만기) : (Number(s.기간) || 0);
  if (지.최장만기 && (Number(s.기간) || 0) > 지.최장만기) {
    경고.push(`${지.이름}은 주담대 만기가 최장 ${지.최장만기}년이라 ${지.최장만기}년으로 셈했습니다.`);
  }
  const 소득 = s.부부공동 ? (Number(s.내소득) || 0) + (Number(s.배우자소득) || 0) : (Number(s.내소득) || 0);
  const 기존 = 기존부채(s);
  const 월예산원 = (소득 * 10000 * DSR.은행) / 12 - 기존.월원;
  const 심사금리 = (Number(s.금리) || 0) / 100 + 스트레스;
  const dsr값 = 월예산원 > 0 ? PV(심사금리 / 12, 만기 * 12, 월예산원) / 10000 : 0;

  // ④ 지역 상한 — 「주택 시가」 구간에 따라 6억 / 4억 / 2억
  const 상한값 = 지역상한(s.지역, 담보);

  const 항목 = [
    {
      이름: 'LTV 한도',
      값: ltv값,
      설명: `${지.이름} ${고른것.이름} ${Math.round(고른것.율 * 100)}% × 담보 ${담보.toLocaleString()}만원`
        + (방공제액 > 0 ? ` − 방공제 ${방공제액.toLocaleString()}만원` : ''),
    },
    {
      이름: 'DSR 한도',
      값: dsr값,
      설명: `${s.부부공동 ? '부부합산' : '본인'} 소득 ${소득.toLocaleString()}만원의 40%에서 기존 빚을 뺀 월 ${Math.round(월예산원).toLocaleString()}원으로, `
        + `심사금리 ${(심사금리 * 100).toFixed(2)}%(실제 ${Number(s.금리)}% + 스트레스 ${(스트레스 * 100).toFixed(2)}%p) · ${만기}년`,
    },
  ];
  if (상한값 != null) {
    항목.push({ 이름: '지역 상한', 값: 상한값, 설명: `${지.이름}은 시가 ${담보.toLocaleString()}만원 구간이라 ${(상한값 / 10000)}억원이 끝입니다` });
  }

  const 한도 = Math.max(0, Math.min(...항목.map((a) => a.값)));
  const 묶은것 = 항목.filter((a) => Math.abs(a.값 - 한도) < 1).map((a) => a.이름);

  return {
    가능: true, 금지이유: null, 한도, 항목, 묶은것, 경고, 지역: 지,
    만기, 스트레스, 심사금리, 소득, 기존, ltv갈래: 고른것, 담보,
  };
}

/** 이 대출을 받으면 매달 얼마를 갚나 (원) */
export function 월상환액(대출만원, 금리퍼센트, 기간년) {
  return PMT((Number(금리퍼센트) || 0) / 100 / 12, (Number(기간년) || 0) * 12, (Number(대출만원) || 0) * 10000);
}
