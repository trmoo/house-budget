import { 청약 as 청약규정 } from '../rules.js';

/**
 * 청약통장을 어떻게 쓰나.
 * ⚠ 세 갈래의 결과가 다르다 — 그대로 두면 0, 담보로 빌리면 잔액의 95%쯤,
 *   해지하면 원금에서 추징을 뺀 값(이자는 통장에서 확인해야 해서 보수적으로 안 센다).
 */
export function 청약쓰기(s) {
  const 잔액 = Number(s.청약잔액) || 0;
  const 고름 = s.청약선택 || '유지';
  if (잔액 <= 0 || 고름 === '유지') {
    return { 고름, 잔액, 쓸수있는돈: 0, 추징: 0, 대출: 0, 연이자: 0, 설명: '그대로 둔다' };
  }
  if (고름 === '담보') {
    const 비율 = (Number(s.청약담보비율) || 0) / 100;
    const 대출 = 잔액 * 비율;
    const 연이자 = (대출 * (Number(s.청약담보금리) || 0)) / 100;
    return {
      고름, 잔액, 대출, 연이자, 추징: 0, 쓸수있는돈: 대출,
      설명: `납입액의 ${Number(s.청약담보비율)}% 를 빌린다 (통장은 그대로 남는다)`,
    };
  }
  // 해지
  const 추징 = 해지추징(s);
  return {
    고름, 잔액, 대출: 0, 연이자: 0, 추징,
    쓸수있는돈: Math.max(0, 잔액 - 추징),
    설명: 추징 > 0 ? `원금에서 소득공제 추징 ${Math.round(추징).toLocaleString()}만원을 뺐다` : '원금 그대로 (이자는 따로)',
  };
}

/**
 * 해지할 때 토해 내는 소득공제 추징액 (어림).
 * 규정은 「공제받은 뒤 납입한 금액(연 300만원 한도) × 6.6%」인데, 앱은 그 누계를 모르므로
 * 「가입 연수 × 연 300만원」과 잔액 중 작은 값으로 어림한다. 화면에 어림이라고 밝힌다.
 */
export function 해지추징(s) {
  const C = 청약규정;
  if (!s.청약공제받음) return 0;
  if ((Number(s.청약가입년) || 0) >= C.추징기간년) return 0;   // 5년이 지나면 추징하지 않는다
  const 잔액 = Number(s.청약잔액) || 0;
  const 공제대상 = Math.min(잔액, (Number(s.청약가입년) || 0) * C.소득공제.연납입한도);
  return 공제대상 * C.추징율;
}

/** 집값에 쓸 수 있는 종잣돈 */
export function 종잣돈(s) {
  const 통장 = 청약쓰기(s);
  const 줄 = [
    { 이름: '예금·적금·CMA', 값: Number(s.예금) || 0 },
    { 이름: '주식·펀드(팔 수 있는 만큼)', 값: Number(s.주식) || 0 },
    { 이름: '지금 사는 집 전세보증금', 값: Number(s.전세보증금) || 0 },
    { 이름: '전세대출(갚아야 하니 뺀다)', 값: -(Number(s.전세대출) || 0) },
    { 이름: '부모님 지원(확정된 것만)', 값: Number(s.부모지원) || 0 },
    {
      이름: 통장.고름 === '담보' ? '청약통장 담보대출' : '청약통장 해지',
      값: 통장.쓸수있는돈,
    },
  ].filter((r) => r.값 !== 0);
  return { 합: 줄.reduce((a, b) => a + b.값, 0), 줄, 청약: 통장 };
}

/** 비상금 — 월 생활비 × 개월 */
export function 비상금(s) {
  return (Number(s.월생활비) || 0) * (Number(s.비상금개월) || 0);
}
