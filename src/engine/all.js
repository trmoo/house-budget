// 세 갈래(은행 · 디딤돌 · 보금자리론)를 나란히 놓고 셈한다.
//
// ★ 검토했던 계산기는 「한도가 큰 쪽」을 골랐다. 그런데 한도가 작아도 금리가 훨씬 싼 쪽이
//   실제로는 나은 경우가 많다(디딤돌 3.8% ↔ 보금자리론 5.4%). 그래서 여기서는
//   ① 그 집을 살 수 있는가 ② 살 수 있다면 매달 얼마를 갚는가 를 함께 보고 고른다.

import { 은행한도, 월상환액, 담보가치 } from './loan.js';
import { 정책후보 } from './policy.js';
import { 취득세, 중개보수, 증여세, 등기비용, 근저당비용 } from './cost.js';
import { 종잣돈, 비상금 } from './cash.js';

/** 대출 한 갈래마다 「필요한 현금」까지 셈한다 */
function 갈래셈(s, 후보, 공통) {
  const 가격 = Number(s.매매가) || 0;
  const 대출 = 후보.가능 ? Math.min(후보.한도, 가격) : 0;
  const 근저당 = 근저당비용(s, 대출);
  const 부대합 = 공통.세금합 + 근저당.합;
  const 필요현금 = Math.max(0, 가격 - 대출) + 부대합 + 공통.여윳돈;
  const 월상환원 = 월상환액(대출, 후보.금리, 후보.만기);
  return {
    ...후보,
    대출, 근저당, 부대합, 필요현금,
    차이: 공통.종잣돈 - 필요현금,
    살수있나: 후보.가능 && 공통.종잣돈 >= 필요현금,
    월상환원,
    총이자: 월상환원 * 후보.만기 * 12 - 대출 * 10000,
  };
}

/**
 * 한 번에 다 셈한다.
 * 돌려주는 것: { 씨, 세금, 갈래들, 추천, 여윳돈줄, … }
 */
export function 계산(s) {
  const 가격 = Number(s.매매가) || 0;
  const 씨 = 종잣돈(s);

  // ── 집값 말고 드는 돈 (대출 갈래와 무관한 것) ──
  const 세 = 취득세(s);
  const 중개 = 중개보수(s);
  const 등기 = 등기비용(s);
  const 증여 = 증여세(s);
  const 세금합 = 세.합 + 중개.합 + 등기.합 + 증여.세액;

  // ── 집값 말고 드는 돈 (살림 준비) ──
  const 여윳돈줄 = [
    { 이름: '비상금', 값: 비상금(s), 설명: `월 생활비 ${(Number(s.월생활비) || 0).toLocaleString()}만원 × ${s.비상금개월}개월` },
    { 이름: '가전·가구', 값: Number(s.가전가구) || 0 },
    { 이름: '이사비·기타', 값: Number(s.이사비) || 0 },
    { 이름: '수리·인테리어', 값: Number(s.수리비) || 0, 설명: '구축이면 도배·장판·욕실만 해도 적지 않다' },
  ];
  const 여윳돈 = 여윳돈줄.reduce((a, b) => a + b.값, 0);

  const 공통 = { 세금합, 여윳돈, 종잣돈: 씨.합 };

  // ── 세 갈래 ──
  const 은행 = 은행한도(s);
  const 은행후보 = {
    키: '은행', 이름: '시중은행 주택담보대출', 가능: 은행.가능, 금지이유: 은행.금지이유,
    한도: 은행.한도, 금리: Number(s.금리) || 0, 만기: 은행.만기,
    항목: 은행.항목, 묶은것: 은행.묶은것, 경고: 은행.경고,
    금리설명: `직접 적은 금리 ${Number(s.금리)}%. DSR 심사는 스트레스를 얹은 ${(은행.심사금리 * 100).toFixed(2)}% 로 한다.`,
    은행상세: 은행,
  };
  const 갈래들 = [은행후보, ...정책후보(s)].map((후보) => 갈래셈(s, 후보, 공통));

  // ── 어느 쪽이 나은가 ──
  const 살수있는것 = 갈래들.filter((g) => g.살수있나);
  let 추천 = null;
  let 추천이유 = '';
  if (살수있는것.length > 0) {
    추천 = 살수있는것.reduce((a, b) => (b.월상환원 < a.월상환원 ? b : a));
    추천이유 = 살수있는것.length === 1
      ? '이 집을 살 수 있는 길은 이것뿐입니다.'
      : '살 수 있는 길 가운데 매달 갚는 돈이 가장 적습니다.';
  } else {
    const 가능한것 = 갈래들.filter((g) => g.가능);
    if (가능한것.length > 0) {
      추천 = 가능한것.reduce((a, b) => (b.차이 > a.차이 ? b : a));
      추천이유 = '지금은 어느 쪽으로도 모자랍니다. 그 가운데 가장 덜 모자란 쪽입니다.';
    }
  }

  return {
    씨, 가격,
    세금: { 취득세: 세, 중개, 등기, 증여, 합: 세금합 },
    여윳돈줄, 여윳돈,
    갈래들, 추천, 추천이유,
    담보: 담보가치(s),
  };
}

/**
 * 지금 종잣돈으로 살 수 있는 가장 비싼 집.
 * ⚠ 매매가를 올리면 시세도 같은 비율로 올라간다고 본다(안 그러면 담보가치가 안 맞는다).
 */
export function 최대매수가(s) {
  const 가격 = Number(s.매매가) || 1;
  const 비율 = (Number(s.kb시세) || 0) > 0 ? s.kb시세 / 가격 : 0;
  const 되나 = (값) => {
    const s2 = { ...s, 매매가: 값, kb시세: 비율 ? 값 * 비율 : 0 };
    const r = 계산(s2);
    return r.추천 ? r.추천.살수있나 : false;
  };
  let 아래 = 0;
  let 위 = Math.max(20000, (종잣돈(s).합 + 100000) * 4);   // 셈용 — 이진 탐색의 위쪽 끝
  if (되나(위)) return { 값: 위, 넘침: true };
  for (let i = 0; i < 44; i += 1) {
    const 가운데 = (아래 + 위) / 2;
    if (되나(가운데)) 아래 = 가운데; else 위 = 가운데;
  }
  return { 값: 아래, 넘침: false };
}

/** 조건을 하나씩 바꿔 보면 한도와 살 수 있는 값이 얼마나 달라지나 */
export function 민감도(s) {
  const 바탕 = 계산(s);
  const 바탕한도 = 바탕.추천 ? 바탕.추천.대출 : 0;
  const 바탕최대 = 최대매수가(s).값;

  const 바탕은행 = 바탕.갈래들[0].대출;

  const 재보기 = (이름, 바꿈, 설명) => {
    const s2 = { ...s, ...바꿈 };
    const r = 계산(s2);
    const 한도 = r.추천 ? r.추천.대출 : 0;
    const 최대 = 최대매수가(s2).값;
    return {
      이름, 설명,
      추천이름: r.추천 ? r.추천.이름 : '없음',
      한도, 한도차: 한도 - 바탕한도,
      은행: r.갈래들[0].대출, 은행차: r.갈래들[0].대출 - 바탕은행,
      최대, 최대차: 최대 - 바탕최대,
    };
  };

  return {
    바탕: { 한도: 바탕한도, 최대: 바탕최대, 은행: 바탕은행, 추천이름: 바탕.추천 ? 바탕.추천.이름 : '없음' },
    줄: [
      재보기('대출 금리가 1%p 오르면', { 금리: (Number(s.금리) || 0) + 1 }, '은행 심사 금리가 함께 올라 은행 한도가 줄어든다(정책대출 금리는 따로 정해져 있어 영향이 없다)'),
      // 셈용 — 금리를 0% 아래로는 내리지 않는다
      재보기('대출 금리가 1%p 내리면', { 금리: Math.max(0.1, (Number(s.금리) || 0) - 1) }, ''),
      재보기('종잣돈이 5,000만원 더 있으면', { 예금: (Number(s.예금) || 0) + 5000 }, '대출 한도는 그대로지만 살 수 있는 값이 오른다'),
      재보기('내 연봉이 1,000만원 오르면', { 내소득: (Number(s.내소득) || 0) + 1000 }, 'DSR·DTI 가 묶고 있을 때만 효과가 있다'),
      재보기('기존 빚을 다 갚으면', { 신용잔액: 0, 마통한도: 0, 학자금월: 0 }, '마이너스통장은 한도만 없애도 한도가 늘어난다'),
    ],
  };
}
