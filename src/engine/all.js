/*! 내 집 예산 계산기 · © 2026 티쳐무 · 모든 권리 보유 */
// 세 갈래(은행 · 디딤돌 · 보금자리론)를 나란히 놓고 셈한다.
//
// ★ 검토했던 계산기는 「한도가 큰 쪽」을 골랐다. 그런데 한도가 작아도 금리가 훨씬 싼 쪽이
//   실제로는 나은 경우가 많다(디딤돌 3.8% ↔ 보금자리론 5.4%). 그래서 여기서는
//   ① 그 집을 살 수 있는가 ② 살 수 있다면 매달 얼마를 갚는가 를 함께 보고 고른다.

import { 은행한도, 월상환액, 담보가치 } from './loan.js';
import { 정책후보 } from './policy.js';
import { 취득세, 중개보수, 증여세, 등기비용, 근저당비용 } from './cost.js';
import { 종잣돈, 비상금 } from './cash.js';

/**
 * 대출 한 갈래마다 「필요한 현금」까지 셈한다.
 *
 * ★★ 여기서 **갚는 돈을 무슨 금액으로 셈하는가**가 추천을 좌우한다 (2026-10-10 검토에서 잡은 결함).
 *   예전에는 갈래마다 **한도까지 꽉 빌린 값**으로 월 상환액을 셈해 견줬다. 그러면
 *   금리가 비싸도 **한도가 작은 쪽이 「매달 덜 낸다」며 이긴다.** 실제로 기본값에서
 *   디딤돌 3.8%(3.2억, 월 149만) 를 제치고 은행 4%(2.5억, 월 120만) 가 추천됐는데,
 *   같은 2.5억으로 견주면 디딤돌이 월 2.8만원 싸다(30년 약 1,000만원).
 *   → **한도까지 빌릴 까닭이 없다.** 종잣돈으로 모자라는 만큼만 빌리면 되고,
 *     그 금액은 갈래와 상관없이 같으므로 그때 비로소 금리가 싼 쪽이 이긴다.
 */
function 갈래셈(s, 후보, 공통) {
  const 가격 = Number(s.매매가) || 0;
  const 한도까지 = 후보.가능 ? Math.min(후보.한도, 가격) : 0;
  const 근저당 = 근저당비용(s, 한도까지);
  const 부대합 = 공통.세금합 + 근저당.합;
  const 필요현금 = Math.max(0, 가격 - 한도까지) + 부대합 + 공통.여윳돈;
  const 차이 = 공통.종잣돈 - 필요현금;
  const 살수있나 = 후보.가능 && 차이 >= 0;

  /* 종잣돈이 남는다면 그만큼 덜 빌리면 된다 — 이것이 **실제로 빌릴 돈**이다. */
  const 쓸대출 = Math.max(0, 한도까지 - Math.max(0, 차이));
  const 월상환원 = 월상환액(쓸대출, 후보.금리, 후보.만기);
  const 만기 = Number(후보.만기) || 0;   // 받을 수 없는 갈래는 만기가 없다 (NaN 방지)

  return {
    ...후보,
    대출: 한도까지, 쓸대출, 근저당, 부대합, 필요현금, 차이, 살수있나,
    // ⚠ 「받을 수는 있는데 한 푼도 안 나오는」 상태를 따로 표시한다.
    //   소득이 0 이면 DSR 한도가 0 이 되는데, 그때 「가능 · 0원」만 보이면 고장처럼 읽힌다.
    한도0: 후보.가능 && 후보.한도 <= 0,
    월상환원,
    한도까지월상환원: 월상환액(한도까지, 후보.금리, 만기),
    총이자: Math.max(0, 월상환원 * 만기 * 12 - 쓸대출 * 10000),
  };
}

/**
 * 한 번에 다 셈한다.
 * 돌려주는 것: { 씨, 세금, 갈래들, 추천, 여윳돈줄, … }
 */
export function 계산(s) {
  const 가격 = Number(s.매매가) || 0;
  const 씨 = 종잣돈(s);

  // ── 집값 말고 드는 돈 (대출 갈래와 무관한 것) ──
  const 세 = 취득세(s);
  const 중개 = 중개보수(s);
  const 등기 = 등기비용(s);
  const 증여 = 증여세(s);
  const 세금합 = 세.합 + 중개.합 + 등기.합 + 증여.세액;

  // ── 집값 말고 드는 돈 (살림 준비) ──
  const 여윳돈줄 = [
    { 이름: '비상금', 값: 비상금(s), 설명: `월 생활비 ${(Number(s.월생활비) || 0).toLocaleString()}만원 × ${s.비상금개월}개월` },
    { 이름: '가전·가구', 값: Number(s.가전가구) || 0 },
    { 이름: '이사비·기타', 값: Number(s.이사비) || 0 },
    { 이름: '수리·인테리어', 값: Number(s.수리비) || 0, 설명: '구축이면 도배·장판·욕실만 해도 적지 않다' },
  ];
  const 여윳돈 = 여윳돈줄.reduce((a, b) => a + b.값, 0);

  const 공통 = { 세금합, 여윳돈, 종잣돈: 씨.합 };

  // ── 세 갈래 ──
  const 은행 = 은행한도(s);
  const 은행후보 = {
    키: '은행', 이름: '시중은행 주택담보대출', 가능: 은행.가능, 금지이유: 은행.금지이유,
    한도: 은행.한도, 금리: Number(s.금리) || 0, 만기: 은행.만기,
    항목: 은행.항목, 묶은것: 은행.묶은것, 경고: 은행.경고,
    금리설명: `직접 적은 금리 ${Number(s.금리)}%. DSR 심사는 스트레스를 얹은 ${(은행.심사금리 * 100).toFixed(2)}% 로 한다.`,
    은행상세: 은행,
  };
  const 갈래들 = [은행후보, ...정책후보(s)].map((후보) => 갈래셈(s, 후보, 공통));

  // ★ 대출이 하나도 안 나오는 사람(규제지역 2주택 등)도 **현금으로는 살 수 있다**.
  //   이것을 빼 두면 「살 수 있는 값 0원」이라는 거짓말을 하게 된다(검토에서 잡았다).
  const 현금만 = 갈래셈(s, {
    키: '현금', 이름: '대출 없이 현금으로', 가능: true, 금지이유: null,
    한도: 0, 금리: 0, 만기: 0, 항목: [], 묶은것: ['매매가'], 경고: [],
  }, 공통);

  // ── 어느 쪽이 나은가 ──
  const 살수있는것 = 갈래들.filter((g) => g.살수있나);
  let 추천 = null;
  let 추천이유 = '';
  if (살수있는것.length > 0) {
    /* 같은 금액(쓸대출)으로 견주므로 여기서는 금리가 싼 쪽이 이긴다.
       매달 갚는 돈이 거의 같으면(만기가 달라서 그럴 수 있다) 이자를 덜 내는 쪽을 고른다. */
    추천 = 살수있는것.reduce((a, b) => {
      const 차 = b.월상환원 - a.월상환원;
      if (Math.abs(차) > 1000) return 차 < 0 ? b : a;   // 셈용 — 월 1,000원 안쪽이면 같다고 본다
      return b.총이자 < a.총이자 ? b : a;
    });
    if (추천.쓸대출 <= 0) 추천이유 = '종잣돈으로 충분해서 대출이 필요 없습니다.';
    else if (살수있는것.length === 1) 추천이유 = '이 집을 살 수 있는 길은 이것뿐입니다.';
    else 추천이유 = `같은 ${Math.round(추천.쓸대출).toLocaleString()}만원을 빌린다고 볼 때 매달 갚는 돈이 가장 적습니다.`;
  } else {
    const 가능한것 = 갈래들.filter((g) => g.가능 && g.한도 > 0);
    if (가능한것.length > 0) {
      추천 = 가능한것.reduce((a, b) => (b.차이 > a.차이 ? b : a));
      추천이유 = '지금은 어느 쪽으로도 모자랍니다. 그 가운데 가장 덜 모자란 쪽입니다.';
    }
  }

  return {
    씨, 가격,
    세금: { 취득세: 세, 중개, 등기, 증여, 합: 세금합 },
    여윳돈줄, 여윳돈,
    갈래들, 추천, 추천이유, 현금만,
    담보: 담보가치(s),
  };
}

/**
 * 지금 종잣돈으로 살 수 있는 가장 비싼 집.
 * ⚠ 매매가를 올리면 시세도 같은 비율로 올라간다고 본다(안 그러면 담보가치가 안 맞는다).
 */
export function 최대매수가(s) {
  const 가격 = Number(s.매매가) || 1;
  const 비율 = (Number(s.kb시세) || 0) > 0 ? s.kb시세 / 가격 : 0;
  const 되나 = (값) => {
    const s2 = { ...s, 매매가: 값, kb시세: 비율 ? 값 * 비율 : 0 };
    const r = 계산(s2);
    // 대출을 받으면 필요한 현금은 줄기만 하므로, 한 갈래라도 열려 있으면 추천 쪽이 기준이 된다.
    // 세 갈래가 모두 막혔을 때만 「현금으로만 사기」를 본다.
    return r.추천 ? r.추천.살수있나 : r.현금만.살수있나;
  };
  let 아래 = 0;
  let 위 = Math.max(20000, (종잣돈(s).합 + 100000) * 4);   // 셈용 — 이진 탐색의 위쪽 끝
  if (되나(위)) return { 값: 위, 넘침: true, 막힌까닭: null };
  for (let i = 0; i < 44; i += 1) {
    const 가운데 = (아래 + 위) / 2;
    if (되나(가운데)) 아래 = 가운데; else 위 = 가운데;
  }
  return { 값: 아래, 넘침: false, 막힌까닭: 아래 > 0 ? null : 왜영원인가(s) };
}

/**
 * 「살 수 있는 값」이 0 으로 나오는 까닭.
 * ⚠ 0 만 덩그러니 보여 주면 고장인지 답인지 알 수 없다 — 그래서 까닭을 함께 돌려준다.
 *   집값을 0 으로 놓아도 드는 돈(살림 준비 + 등기·수수료)이 종잣돈보다 크면,
 *   집값을 아무리 낮춰도 못 사므로 이진 탐색이 0 에서 멈춘다. 고장이 아니라 답이다.
 */
function 왜영원인가(s) {
  const 바닥집 = 계산({ ...s, 매매가: 0, kb시세: 0 });
  const 부대 = 바닥집.세금.합;
  const 바닥 = 부대 + 바닥집.여윳돈;
  const 씨 = 바닥집.씨.합;
  const 금지 = 바닥집.갈래들.filter((g) => !g.가능).map((g) => g.금지이유);
  if (씨 <= 0) return { 종류: '종잣돈없음', 바닥, 부대, 여윳돈: 바닥집.여윳돈, 씨, 금지 };
  if (씨 < 바닥) return { 종류: '기본비용초과', 바닥, 부대, 여윳돈: 바닥집.여윳돈, 씨, 금지 };
  return { 종류: '그밖', 바닥, 부대, 여윳돈: 바닥집.여윳돈, 씨, 금지 };
}

/** 조건을 하나씩 바꿔 보면 한도와 살 수 있는 값이 얼마나 달라지나 */
export function 민감도(s) {
  const 바탕 = 계산(s);
  const 바탕한도 = 바탕.추천 ? 바탕.추천.대출 : 0;
  const 바탕최대 = 최대매수가(s).값;

  const 바탕은행 = 바탕.갈래들[0].대출;

  const 재보기 = (이름, 바꿈, 설명) => {
    const s2 = { ...s, ...바꿈 };
    const r = 계산(s2);
    const 한도 = r.추천 ? r.추천.대출 : 0;
    const 최대 = 최대매수가(s2).값;
    return {
      이름, 설명,
      추천이름: r.추천 ? r.추천.이름 : '없음',
      한도, 한도차: 한도 - 바탕한도,
      은행: r.갈래들[0].대출, 은행차: r.갈래들[0].대출 - 바탕은행,
      최대, 최대차: 최대 - 바탕최대,
    };
  };

  return {
    바탕: { 한도: 바탕한도, 최대: 바탕최대, 은행: 바탕은행, 추천이름: 바탕.추천 ? 바탕.추천.이름 : '없음' },
    줄: [
      재보기('대출 금리가 1%p 오르면', { 금리: (Number(s.금리) || 0) + 1 }, '은행 심사 금리가 함께 올라 은행 한도가 줄어든다(정책대출 금리는 따로 정해져 있어 영향이 없다)'),
      // 셈용 — 금리를 0% 아래로는 내리지 않는다
      재보기('대출 금리가 1%p 내리면', { 금리: Math.max(0.1, (Number(s.금리) || 0) - 1) }, ''),
      재보기('종잣돈이 5,000만원 더 있으면', { 예금: (Number(s.예금) || 0) + 5000 }, '대출 한도는 그대로지만 살 수 있는 값이 오른다'),
      재보기('내 연봉이 1,000만원 오르면', { 내소득: (Number(s.내소득) || 0) + 1000 }, 'DSR·DTI 가 묶고 있을 때만 효과가 있다'),
      /* ⚠ 빚을 갚으려면 **돈이 든다.** 예전에는 잔액만 0 으로 두고 종잣돈을 그대로 두어,
         신용대출 8천만원이 있는 사람에게 「살 수 있는 값 5.2억」(실제 2.7억) 이라고 했다.
         마이너스통장은 한도만 줄여도 되므로 돈이 들지 않는다 — 신용대출 잔액만 뺀다. */
      재보기('기존 빚을 다 갚으면',
        { 신용잔액: 0, 마통한도: 0, 학자금월: 0, 예금: Math.max(0, (Number(s.예금) || 0) - (Number(s.신용잔액) || 0)) },
        '갚는 데 쓴 돈만큼 종잣돈도 줄여서 셈했다. 마이너스통장은 한도만 없애도 되니 돈이 들지 않는다'),
    ],
  };
}
