import { 세금, 부대비용 } from '../rules.js';

/** 1주택 일반 취득세율 — 6억 이하 1%, 6~9억 구간 산식, 9억 초과 3% */
export function 취득세율(가격만원) {
  const 가격 = Number(가격만원) || 0;
  const T = 세금.취득세;
  if (가격 <= T.낮은구간) return T.낮은세율;
  if (가격 > T.높은구간) return T.높은세율;
  const 억 = 가격 / 10000;
  const 율 = ((억 / 3) * 2 - 3) / 100;
  // 법이 소수 다섯째 자리에서 반올림하라고 한다(0.01%p 단위)
  return Math.round(율 * 10000) / 10000;
}

/**
 * 취득세 한 묶음 (본세 + 지방교육세 + 농어촌특별세 − 생애최초 감면)
 */
export function 취득세(s) {
  const T = 세금.취득세;
  const G = 세금.생애최초감면;
  const 가격 = Number(s.매매가) || 0;
  const 면적 = Number(s.전용면적) || 0;
  const 조정 = s.지역 === '규제';          // 규제지역 = 조정대상지역 + 투기과열지구
  const 가진것 = Number(s.주택수) || 0;
  const 취득후 = 가진것 + 1;
  const 일시적2주택 = 취득후 === 2 && !!s.처분조건;

  let 중과율 = null;
  let 중과사유 = null;
  if (취득후 === 2 && 조정 && !일시적2주택) {
    중과율 = T.중과.조정2주택;
    중과사유 = '조정대상지역에서 2주택이 되어 8% 중과';
  } else if (취득후 >= 3) {
    if (조정) { 중과율 = T.중과.조정3주택이상; 중과사유 = '조정대상지역 3주택 이상이라 12% 중과'; }
    else if (취득후 === 3) { 중과율 = T.중과.비조정3주택; 중과사유 = '비조정지역 3주택이라 8% 중과'; }
    else { 중과율 = T.중과.비조정4주택이상; 중과사유 = '비조정지역 4주택 이상이라 12% 중과'; }
  }

  const 세율 = 중과율 ?? 취득세율(가격);
  const 본세 = 가격 * 세율;
  const 교육세 = 중과율 ? 가격 * T.중과지방교육세 : 본세 * T.지방교육세비율;
  const 큰면적 = 면적 > T.농특세.면적기준;
  let 농특율 = 0;
  if (큰면적) {
    if (중과율 === T.중과.조정2주택 || 중과율 === T.중과.비조정3주택) 농특율 = T.농특세.중과8;
    else if (중과율) 농특율 = T.농특세.중과12;
    else 농특율 = T.농특세.일반;
  }
  const 농특세 = 가격 * 농특율;

  // 생애최초 감면 — 무주택자가 생애최초로 12억 이하 집을 유상으로 살 때 본세에서 뺀다
  let 감면 = 0;
  let 감면설명 = null;
  if (s.생애최초 && 가진것 === 0 && !중과율) {
    if (가격 <= G.가격상한) {
      감면 = Math.min(본세, G.한도);
      감면설명 = `생애최초 감면 ${G.한도}만원 한도`;
    } else {
      감면설명 = `생애최초라도 집값이 ${(G.가격상한 / 10000)}억원을 넘어 감면이 없다`;
    }
  }

  const 합 = Math.max(0, 본세 - 감면) + 교육세 + 농특세;
  return {
    세율, 본세, 교육세, 농특세, 농특율, 감면, 감면설명, 합,
    중과율, 중과사유, 일시적2주택, 큰면적,
    설명: `${(세율 * 100).toFixed(2).replace(/\.?0+$/, '')}%`
      + (중과율 ? ' (중과)' : '')
      + ` + 지방교육세${큰면적 ? ' + 농특세 0.2%' : ''}`
      + (감면 > 0 ? ` − 감면 ${감면}만원` : ''),
  };
}

/** 중개보수 (상한요율 + 부가세) */
export function 중개보수(s) {
  const 가격 = Number(s.매매가) || 0;
  const 줄 = 부대비용.중개보수.find(([미만]) => 가격 < 미만) || 부대비용.중개보수[부대비용.중개보수.length - 1];
  const [, 요율, 한도] = 줄;
  let 기본 = 가격 * 요율;
  let 한도걸림 = false;
  if (한도 > 0 && 기본 > 한도) { 기본 = 한도; 한도걸림 = true; }
  const 부가세 = 기본 * 부대비용.부가세;
  return {
    요율, 한도, 한도걸림, 기본, 부가세, 합: 기본 + 부가세,
    설명: `상한요율 ${(요율 * 100).toFixed(1)}%${한도걸림 ? ` (한도 ${한도}만원)` : ''} + 부가세 10%`,
  };
}

/**
 * 소유권이전 등기 비용.
 * ⚠ 「등록면허세」는 없다 — 집을 사는 등기의 등록세는 2011년에 취득세로 합쳐졌다.
 *   실제로 드는 것은 국민주택채권 할인비 · 인지세 · 등기신청수수료 · 법무사 보수다.
 */
export function 법무사상한(과세표준만원) {
  const E = 부대비용.등기;
  const 과표 = Number(과세표준만원) || 0;
  let 고른것 = E.법무사표[0];
  for (const 줄 of E.법무사표) if (과표 >= 줄[0]) 고른것 = 줄;
  const [하한, 기본, 비율] = 고른것;
  return 기본 + (과표 - 하한) * 비율;
}

export function 등기비용(s) {
  const E = 부대비용.등기;
  const 가격 = Number(s.매매가) || 0;
  // 채권 매입률은 「특별시·광역시」와 「그 밖」이 다르다. 지역 선택만으로는 광역시를 알 수 없어 따로 묻는다.
  const 큰도시 = !!s.광역시;
  const 공시 = Number(s.공시가격) || 0;
  const 시가표준액 = 공시 > 0 ? 공시 : 가격 * E.시가표준액비율;

  const 매입줄 = E.채권매입률.find(([미만]) => 시가표준액 < 미만) || E.채권매입률[E.채권매입률.length - 1];
  const 매입률 = 큰도시 ? 매입줄[1] : 매입줄[2];
  // 1만원 미만 단수는 5천원 이상이면 올리고 아니면 버린다(별표 비고). 단위가 만원이라 반올림이 곧 그 규칙이다.
  const 매입액 = Math.round(시가표준액 * 매입률);
  const 할인율 = (Number(s.채권할인율) || 0) / 100;
  const 채권할인비 = 매입액 * 할인율;

  const 인지줄 = E.인지세.find(([이하]) => 가격 <= 이하) || E.인지세[E.인지세.length - 1];
  const 인지세 = 인지줄[1];

  const 상한 = (법무사상한(가격) + E.법무사가산 + E.법무사대행료) * 1.1;   // 부가세 포함
  let 법무사 = 상한;
  let 법무사설명 = `협회 보수기준 상한 + 대행료 + 부가세`;
  if (s.법무사직접) { 법무사 = 0; 법무사설명 = '직접 등기한다고 해서 0'; }
  else if (s.법무사따로) { 법무사 = Number(s.법무사보수) || 0; 법무사설명 = `직접 적은 값 (상한은 ${Math.round(상한)}만원)`; }

  const 줄 = [
    {
      이름: '국민주택채권 할인비',
      값: 채권할인비,
      설명: 매입률 === 0
        ? '시가표준액 2천만원 미만은 사지 않는다'
        : `시가표준액 ${Math.round(시가표준액).toLocaleString()}만원 × ${(매입률 * 1000).toFixed(0)}/1000 = ${매입액.toLocaleString()}만원어치를 사서 ${s.채권할인율}% 손해 보고 되판다`,
    },
    { 이름: '인지세', 값: 인지세, 설명: 인지세 === 0 ? '주택 1억원 이하는 비과세' : '거래금액 구간별 정액' },
    { 이름: '등기신청수수료', 값: E.등기신청수수료, 설명: '방문 18,000원 (2025-08-01 올랐다)' },
    { 이름: '법무사 보수', 값: 법무사, 설명: 법무사설명 },
  ];
  return { 합: 줄.reduce((a, b) => a + b.값, 0), 줄, 매입률, 매입액, 시가표준액, 큰도시, 상한 };
}

/** 근저당권 설정 — 설정비는 은행이 내고, 빌리는 사람은 채권 할인비와 인지세 절반을 낸다 */
export function 근저당비용(s, 대출만원) {
  const E = 부대비용.등기;
  const 대출 = Number(대출만원) || 0;
  if (대출 <= 0) return { 합: 0, 줄: [], 메모: E.근저당메모 };
  const 채권최고액 = 대출 * E.채권최고액비율;
  const 채권할인비 = 채권최고액 * E.근저당채권률 * ((Number(s.채권할인율) || 0) / 100);
  const 대출인지줄 = E.대출인지세.find(([이하]) => 대출 <= 이하) || E.대출인지세[E.대출인지세.length - 1];
  const 인지절반 = 대출인지줄[1] / 2;
  const 줄 = [
    { 이름: '국민주택채권 할인비', 값: 채권할인비, 설명: `채권최고액 ${Math.round(채권최고액).toLocaleString()}만원 × 1% × 할인율 ${s.채권할인율}%` },
    { 이름: '인지세 절반', 값: 인지절반, 설명: '은행과 반씩 나눈다' },
  ];
  return { 합: 줄.reduce((a, b) => a + b.값, 0), 줄, 메모: E.근저당메모 };
}

/** 증여세 — 부모님이 보태 주는 돈에 붙는다 */
export function 증여세(s) {
  const Z = 세금.증여세;
  const 받은 = Number(s.부모지원) || 0;
  if (!s.증여계산 || 받은 <= 0) {
    return { 셈함: false, 세액: 0, 받은, 공제: 0, 과표: 0, 설명: '셈하지 않음' };
  }
  const 공제 = Z.공제.성년자녀10년 + (s.증여혼인공제 ? Z.공제.혼인출산합산 : 0);
  const 과표 = Math.max(0, 받은 - 공제);
  const 줄 = Z.세율표.find(([상한]) => 과표 <= 상한) || Z.세율표[Z.세율표.length - 1];
  const [, 율, 누진] = 줄;
  const 산출 = Math.max(0, 과표 * 율 - 누진);
  const 세액 = 산출 * (1 - Z.신고세액공제);
  return {
    셈함: true, 세액, 받은, 공제, 과표, 율, 누진, 산출,
    설명: 과표 === 0
      ? `공제 ${공제.toLocaleString()}만원 안에 들어 세금이 없다`
      : `(${받은.toLocaleString()} − 공제 ${공제.toLocaleString()}) × ${Math.round(율 * 100)}% − ${누진.toLocaleString()} → 신고세액공제 3% 적용`,
  };
}
